def gen7_names(kind):
    names = set()
    for f in os.listdir(GEN7):
        if f.endswith(".mm0"):
            for m in re.finditer(r"^%s ([A-Za-z0-9_.]+)" % kind, open(os.path.join(GEN7, f)).read(), re.M):
                names.add(m.group(1))
    return names


def gen7_defs():
    names = set()
    for f in os.listdir(GEN7):
        if f.endswith(".mm0"):
            for m in re.finditer(r"^def (\S+)", open(os.path.join(GEN7, f)).read(), re.M):
                names.add(m.group(1))
    return names


def write_perdef(r, path):
    pd = perdef.PerDef(r)
    have = gen7_defs()
    items = ['import "gen7_lib.mm1";\n',
             "-- G7 C3 (generated by tools/gen7/refl_lib.py): code defs and per-def lemmas of one reflection.\n"]
    for op, body, kind, ref, line in r.decls:
        if kind == "def" and line is not None:
            nm = r.terms[ref].name
            if nm in have:
                continue
            items.append(line + "\n")
    inv = {oid: key for key, oid in r.lem.items()}
    lines = {ref: line for op, body, kind, ref, line in r.decls if kind == "axiom"}
    n = 0
    for oid in sorted(inv):
        kind, tid, var = inv[oid]
        if not r.terms[tid].is_def:
            continue
        pd.public(kind, tid, var, lines[oid])
        n += 1
    # extra per-def lemmas wanted by hand glue (GEN7_NEED="pf:ctmHalts,nf:csfThInconsistent"): proved
    # here although no reflected proof uses them
    for want in filter(None, os.environ.get("GEN7_NEED", "").split(",")):
        kind, nm = want.split(":")
        if nm in r.tname:
            pd.need(kind, r.tname[nm])
    items += pd.out
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(items))
    return n, len(pd.out)


class ReflLib(refl.Refl):
    """refl.Refl over a compiled library (gen7_lib + perdef): every library term, L item and
    per-def lemma is looked up by name in the library instead of being declared."""
    def __init__(self, src, lib, names1):                        # noqa: C901
        self.src, self.lib, self.names1 = src, lib, names1
        self.terms, self.thms = list(lib.terms), list(lib.thms)
        self.tname = {t.name: t.id for t in self.terms}
        self.hname = {t.name: t.id for t in self.thms}
        self.names, self.renamed = set(self.tname) | set(self.hname), []
        self.out_stmts, self.w, self.spec = [], None, []
        self.stats = dict(defs=0, thms=0, in_bytes=0, out_bytes=0, in_cmds=0, out_cmds=0,
                          lib_axioms=0, gen_lemmas=0, gen_lemma_est_cmds=0, alpha_steps=0,
                          side_nodes=0, main_nodes=0, side_hyps=0, conv_alpha=0)
        self.usage = {k: (0, None) for k in refl.LIMITS}
        self.ratio = {"heap": (0.0, None), "store": (0.0, None)}
        self.src_usage = {"heap": (0, None), "store": (0, None)}
        self.limit_fail = []
        self.info, self.tmap, self.hmap, self.why, self.side_omitted = {}, {}, {}, {}, {}
        self.tpl, self.lem, self.decls = {}, {}, []
        T = self.tname
        self.info[T["cV"]] = refl.Info(["n"], {}, {0})
        for t in src.terms:
            if t.name in refl.PRIM and not t.is_def:
                tid = T[refl.PRIM[t.name]]
                self.tmap[t.id] = tid
                self.info[tid] = refl.Info(*refl.src_info(t))
        self.cPr, self.nfr, self.nne, self.aeq = T["cPr"], T["nfr"], T["nne"], T["aeq"]
        self.cnil, self.ctup, self.nfresh, self.cV = T["cnil"], T["ctup"], T["nfresh"], T["cV"]
        for nm in ("nne_sym", "nfr_Vinv", "nfr_fresh", "nfr_tl", "nfr_tr", "aeq_refl", "aeq_sym", "aeq_trans", "cPr_aeq"):
            if nm not in self.hname:
                raise refl.MMBError("library lacks " + nm)

    def add_term(self, name, n, sort):
        return self.tname[name]

    def add_axiom(self, name, n, cx, hyps, concl, cat):
        oid = self.hname.get(name)
        if oid is None:
            raise refl.MMBError("library lacks " + name)
        self.stats["lib_axioms" if cat == "lib" else "gen_lemmas"] += 1
        return oid

    def tr_def(self, t):
        name = self.names1[t.id]
        if not t.unify:
            tid = self.tname[name]
            self.info[tid] = refl.Info(*refl.src_info(t))
            self.tmap[t.id] = tid
            return
        class M:
            terms = self.src.terms
        sn, root, _ = refl.decode_unify(M, t)
        cx = refl.Ctx()
        n = len(t.args)
        for i in range(n):
            cx.mk("var", i)
        leaves = [cx.mk("app", self.cV, (cx.mk("var", i),)) if refl.type_bound(w) else cx.mk("var", i)
                  for i, w in enumerate(t.args)]
        dnodes = [i for i, nd in enumerate(sn) if nd[0] == "dummy"]
        dname = {}
        Tt = self.bal(cx, leaves, {}, "")
        for d in dnodes:
            z = cx.mk("app", self.nfresh, (Tt,))
            dname[d] = z
            Tt = cx.mk("app", self.ctup, (cx.mk("app", self.cV, (z,)), Tt))
        body = self.tr_expr(cx, sn, root, t.args, {}, lambda m: dname[m])
        tid = self.tname[name]
        kinds, deps, rd = refl.src_info(t)
        self.info[tid] = refl.Info(kinds, deps, rd, len(dnodes), (cx.nodes, body, [dname[d] for d in dnodes]))
        self.tmap[t.id] = tid
        self.stats["defs"] += 1

    def needed_defs(self, keep_thms=()):
        """Term ids the public output statements need (transitively through def bodies)."""
        class M:
            terms = self.terms
        need, work = set(), []
        def scan(nodes):
            for nd in nodes:
                if nd[0] == "app" and nd[1] not in need:
                    need.add(nd[1]); work.append(nd[1])
        for op, body, kind, ref, line in self.decls:
            if line is not None and kind == "thm":
                scan(refl.decode_unify(M, self.thms[ref])[0])
        for t in self.lib.thms:
            if t.name in keep_thms:
                scan(refl.decode_unify(M, t)[0])
        for t in self.lib.terms:
            if t.name in keep_thms:
                need.add(t.id); work.append(t.id)
        while work:
            t = self.terms[work.pop()]
            if t.is_def and t.unify:
                scan(refl.decode_unify(M, t)[0])
        return need

    def write_lib(self, path, mm0, libspec, keep=()):
        """Output = the library (theorems local; defs local unless a public statement needs
        them) + the reflected statements. Spec = the library spec without its theorems and
        without the defs made local, + the reflected public statements."""
        need = self.needed_defs(keep)
        w = refl.MMBWriter(path, os.path.dirname(os.path.abspath(path)))
        for srt in self.lib.sorts:
            w.add_sort(srt.mods, srt.name)
        for t in self.terms:
            w.add_term(t)
        for t in self.thms:
            w.add_thm(t)
        keep_def = set()
        for st in self.lib.iter_stmts():
            op = st.op
            if st.kind == "def":
                op = refl.STMT_DEF if st.ref in need else refl.STMT_LOCAL_DEF
                if st.ref in need:
                    keep_def.add(self.terms[st.ref].name)
            elif st.kind == "thm" and self.thms[st.ref].name not in keep:
                op = refl.STMT_LOCAL_THM
            w.add_stmt(op, body=bytes(st.body))
        lines = []
        for op, body, kind, ref, line in self.decls:
            w.add_stmt(op, body=body)
            if line is not None:
                lines.append(line)
        w.finish("rebuild")
        spec, dropped = [], set()
        for kind, name, txt in mm0_statements(open(libspec).read()):
            if kind == "theorem" and name not in keep:
                continue
            if kind == "def" and name not in keep_def:
                dropped.add(name)
                continue
            if kind in ("prefix", "infixl", "infixr", "notation", "coercion") and name in dropped:
                continue
            spec.append(txt)
        with open(mm0, "w", newline="\n") as f:
            f.write("\n".join(spec) + "\n\n-- reflected statements\n" + "\n".join(lines) + "\n")
        return len(lines), len(keep_def)


def mm0_statements(text):
    """Split an .mm0 text into (keyword, name, statement text) at top-level semicolons."""
    out, i, n = [], 0, len(text)
    start, math = 0, False
    while i < n:
        c = text[i]
        if not math and text.startswith("--", i):
            j = text.find("\n", i)
            i = n if j < 0 else j + 1
            if text[start:i].strip().startswith("--") and not text[start:i].strip().count("\n"):
                start = i
            continue
        if c == "$":
            math = not math
        elif c == ";" and not math:
            st = text[start:i + 1].strip()
            lines = [l for l in st.split("\n") if not l.strip().startswith("--")]
            st = "\n".join(lines).strip()
            toks = st.replace("(", " ").split()
            kw = toks[0] if toks else ""
            k = 0
            while k < len(toks) and toks[k] in ("pure", "strict", "provable", "free", "local"):
                k += 1
            kw = toks[k] if k < len(toks) else ""
            nm = toks[k + 1].rstrip(":") if k + 1 < len(toks) else ""
            out.append((kw, nm, st))
            start = i + 1
        i += 1
    return out


