import collections, json, hashlib


class ReflDry(refl.Refl):
    """Pass 1: the reflection without proof bodies (it only collects the code defs, the
    per-def lemmas the side proofs use, and the public statements)."""
    def add_thm_r(self, name, n, cx, concl, hyps, root, pub):
        name = name if pub and name not in self.names else self.uniq(name)
        self.names.add(name)
        uni, ud, uh = self.unify_of(cx, [concl] + list(reversed(hyps)), n)
        th = refl.Thm(len(self.thms), [refl.NATW] * n, uni, name=name)
        th.var_names = ["v%d" % i for i in range(n)]
        th.hyp_names = ["h%d" % i for i in range(len(hyps))]
        self.thms.append(th)
        self.hname[name] = th.id
        self.decls.append((refl.STMT_THM if pub else refl.STMT_LOCAL_THM, b"", "thm", th.id,
                           self.print_decl(th, False) if pub else None))
        return th.id, 0


def term_names_of(terms, objs):
    """Names of the terms (transitively through def bodies) used by the given thms/terms."""
    class M:
        pass
    M.terms = terms
    need, work = set(), []
    def scan(nodes):
        for nd in nodes:
            if nd[0] == "app" and nd[1] not in need:
                need.add(nd[1]); work.append(nd[1])
    for o in objs:
        scan(refl.decode_unify(M, o)[0])
    while work:
        t = terms[work.pop()]
        if t.is_def and t.unify:
            scan(refl.decode_unify(M, t)[0])
    return {terms[i].name for i in need}


class ReflStream(ReflLib):
    """Pass 2: streaming output (statements go to the writer's spool as they are made),
    bounded template cache, and splitting of statements over the mm0-c limits."""
    TPL_CAP = 50000
    SPLIT_SHARE = 4          # a split piece gets at most limit / SPLIT_SHARE heap entries

    def __init__(self, src, lib, names1):
        ReflLib.__init__(self, src, lib, names1)
        self.tpl = collections.OrderedDict()
        self.nsplit = 0
        self.lines = []
        self.limits = dict(refl.LIMITS)
        if os.environ.get("REFL_TEST_HEAP"):          # test hook: pretend mm0-c has a small heap
            self.limits["heap"] = int(os.environ["REFL_TEST_HEAP"])

    def template(self, oid):
        r = self.tpl.get(oid)
        if r is not None:
            self.tpl.move_to_end(oid)
            return r
        class M:
            terms = self.terms
        r = self.tpl[oid] = refl.decode_unify(M, self.thms[oid])
        if len(self.tpl) > self.TPL_CAP:
            self.tpl.popitem(last=False)
        return r

    def open(self, path, libspec, keep, need_names):
        """Write the library statements: theorems local except the gen7 ones (keep); defs
        public iff a public statement needs them (need_names, gen7)."""
        need = term_names_of(self.lib.terms, [t for t in self.lib.thms if t.name in keep] +
                             [t for t in self.lib.terms if t.name in keep or t.name in need_names])
        need |= {t.name for t in self.lib.terms if t.name in keep or t.name in need_names}
        self.w = refl.MMBWriter(path, os.path.dirname(os.path.abspath(path)))
        for srt in self.lib.sorts:
            self.w.add_sort(srt.mods, srt.name)
        keep_def = set()
        for st in self.lib.iter_stmts():
            op = st.op
            if st.kind == "def":
                nm = self.terms[st.ref].name
                op = refl.STMT_DEF if nm in need else refl.STMT_LOCAL_DEF
                if nm in need:
                    keep_def.add(nm)
            elif st.kind == "thm" and self.thms[st.ref].name not in keep:
                op = refl.STMT_LOCAL_THM
            self.w.add_stmt(op, body=bytes(st.body))
        self.spec, dropped = [], set()
        for kind, name, txt in mm0_statements(open(libspec).read()):
            if kind == "theorem" and name not in keep:
                continue
            if kind == "def" and name not in keep_def:
                dropped.add(name)
                continue
            if kind in ("prefix", "infixl", "infixr", "notation", "coercion") and name in dropped:
                continue
            self.spec.append(txt)
        return len(keep_def)

    def add_thm_r(self, name, n, cx, concl, hyps, root, pub, _piece=False):
        name = name if pub and name not in self.names else self.uniq(name)
        self.names.add(name)
        uni, ud, uh = self.unify_of(cx, [concl] + list(reversed(hyps)), n)
        body_b, ncmd = self.emit(cx, n, hyps, root)
        use = dict(self.last_use, ustack=ud, uheap=uh, bv=0)
        if any(use.get(k, 0) > self.limits[k] for k in ("heap", "store", "stack")):
            root = self.split(name, n, cx, concl, hyps, root)
            body_b, ncmd = self.emit(cx, n, hyps, root)
            use = dict(self.last_use, ustack=ud, uheap=uh, bv=0)
        bad = [k for k in self.limits if use.get(k, 0) > self.limits[k]]
        for k in refl.LIMITS:
            if use.get(k, 0) > self.usage[k][0]:
                self.usage[k] = (use[k], name)
        if bad:
            msg = "mm0-c limit after split: " + ", ".join("%s %d > %d" % (k, use[k], self.limits[k]) for k in bad)
            self.limit_fail.append((name, msg))
            raise refl.Untranslatable(msg)
        th = refl.Thm(len(self.thms), [refl.NATW] * n, uni, name=name)
        th.var_names = ["v%d" % i for i in range(n)]
        th.hyp_names = ["h%d" % i for i in range(len(hyps))]
        self.thms.append(th)
        self.hname[name] = th.id
        body = body_b + b"\0"
        self.w.add_stmt(refl.STMT_THM if pub else refl.STMT_LOCAL_THM, body=body)
        if pub:
            self.lines.append((name, self.print_decl(th, False)))
        self.stats["out_cmds"] += ncmd
        self.stats["out_bytes"] += len(body)
        return th.id, len(body)

    # ---- splitting: proof nodes become local lemmas with the parent's args and hyps ----
    def split(self, name, n, cx, concl, hyps, root):
        nodes = cx.nodes
        budget = max(64, self.limits["heap"] // self.SPLIT_SHARE)

        def kids(nd):
            k = nd[0]
            if k == "app":
                return nd[2]
            if k == "thm":
                return nd[3] + nd[2] + (nd[4],)
            if k == "conv":
                return (nd[1], nd[2]) + tuple(self.conv_exprs(cx, nd[3]))
            return ()

        def fits(x):
            seen, st = {x}, [x]
            while st:
                for c in kids(nodes[st.pop()]):
                    if c not in seen:
                        seen.add(c)
                        if len(seen) > budget:
                            return False
                        st.append(c)
            return True
        hypn = tuple(cx.mk("hyp", i) for i in range(len(hyps)))
        varn = tuple(cx.mk("var", i) for i in range(n))
        memo = {}

        def rebuild(x, top):
            if x in memo:
                return memo[x]
            nd = nodes[x]
            if nd[0] not in ("thm", "conv"):
                return x
            if not top and fits(x):
                c = nd[4] if nd[0] == "thm" else nd[1]
                oid, _ = self.add_thm_r(name + "_s", n, cx, c, hyps, x, False)
                self.nsplit += 1
                r = cx.mk("thm", oid, varn, hypn, c)
            elif nd[0] == "thm":
                r = cx.mk("thm", nd[1], nd[2], tuple(rebuild(h, False) for h in nd[3]), nd[4])
            else:
                r = cx.mk("conv", nd[1], rebuild(nd[2], False), nd[3])
            memo[x] = r
            return r
        return rebuild(root, True)

    def finish(self, spec_path, manifest_path, meta):
        for t in self.terms:
            self.w.add_term(t)
        for t in self.thms:
            self.w.add_thm(t)
        self.w.finish("rebuild")
        with open(spec_path, "w", newline="\n") as f:
            f.write("\n".join(self.spec) + "\n\n-- reflected statements\n" + "\n".join(l for _, l in self.lines) + "\n")
        man = dict(meta)
        man["roots"] = [{"output": nm, "statement": l} for nm, l in self.lines]
        man["renamed"] = self.renamed
        man["split_pieces"] = self.nsplit
        man["mm0c_maxima"] = {k: list(v) for k, v in self.usage.items()}
        with open(manifest_path, "w") as f:
            json.dump(man, f, indent=1)
        return len(self.lines)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def restrict_to_cone(src, roots):
    """Make src.iter_stmts skip every theorem outside the dependency cone of the named roots
    (transitive closure over the theorems their proofs cite). Defs, terms and axioms are kept.
    Returns (kept, total). Used by --cone; the per-def lemma generator then only sees the defs
    the cone's proofs need (an unpruned closure can stall in it, lanes/D3CHECK.md section 3)."""
    from translator.mmb_format import PROOF_THM, PROOF_THM_SAVE
    deps = {}
    for st in src.iter_stmts():
        if st.kind in ("thm", "local_thm"):
            deps[st.ref] = {d for op, d in st.cmds() if op in (PROOF_THM, PROOF_THM_SAVE)}
    todo = []
    byname = {t.name: t for t in src.thms}
    src.thm_by_name = lambda n: byname[n]
    for name in roots:
        try:
            todo.append(src.thm_by_name(name).id)
        except KeyError:
            raise SystemExit("--cone: no theorem named " + name)
    cone = set()
    while todo:
        i = todo.pop()
        if i not in cone:
            cone.add(i)
            todo.extend(deps.get(i, ()))
    whole = src.iter_stmts

    def iter_cone():
        for st in whole():
            if st.kind in ("thm", "local_thm") and st.ref not in cone:
                continue
            yield st
    src.iter_stmts = iter_cone
    return len(cone & set(deps)), len(deps)


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("src"); ap.add_argument("out")
    ap.add_argument("--max", type=int, default=None)
    ap.add_argument("--pub", default="pub", help="pub | all | none: which reflected theorems are public")
    ap.add_argument("--roots", default=None, help="file with source theorem names to make public (overrides --pub)")
    ap.add_argument("--stage", default="all")
    ap.add_argument("--nfr", default=None,
                    help="comma-separated source def names whose freshness lemmas nfr_cD are generated even if no reflected proof needs them")
    ap.add_argument("--cone", action="store_true",
                    help="reflect only the dependency cone of the --roots theorems (theorems outside it are skipped)")
    ns = ap.parse_args()
    # absolute paths: lcheck.py runs with cwd pa-mm0, so a relative OUTDIR would land under pa-mm0/
    ns.src, ns.out = os.path.abspath(ns.src), os.path.abspath(ns.out)
    t0 = time.time()
    pubspec = ns.pub
    if ns.roots:
        pubspec = frozenset(l.strip() for l in open(ns.roots) if l.strip() and not l.startswith("#"))
    os.makedirs(os.path.join(ns.out, "gen7"), exist_ok=True)
    src = refl.read_mmb(ns.src)
    if ns.cone:
        if not ns.roots:
            raise SystemExit("--cone needs --roots")
        print("cone: %d of %d theorems kept" % restrict_to_cone(src, sorted(pubspec)))
    r = ReflDry(src)
    r.run(ns.max, pubspec)
    if ns.nfr:
        byname = {t.name: t.id for t in src.terms}
        for nm in ns.nfr.split(","):
            r.lemma("nfr", r.tmap[byname[nm]])
    pd_path = os.path.join(ns.out, "gen7", "perdef.mm1")
    npd, nitems = write_perdef(r, pd_path)
    print("pass 1: %d theorems; perdef: %d per-def lemmas, %d items (%.1fs)" % (r.stats["thms"], npd, nitems, time.time() - t0))
    if ns.stage == "perdef":
        return 0
    subprocess.check_call([sys.executable, os.path.join(HERE, "c2", "mk0.py"), pd_path, pd_path[:-1] + "0"])
    env = dict(os.environ, GEN7_SRC=ns.out, LCHECK_OUT=os.path.join(ns.out, "lc"))
    pr_ = subprocess.run([sys.executable, os.path.join(HERE, "lcheck.py"), "gen7/perdef"], cwd=os.path.join(ROOT, "pa-mm0"),
                         env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
    print("\n".join(l for l in pr_.stdout.splitlines() if re.match(r"(compile rc|check rc|LOCAL|false)", l)))
    print("library compiled (%.1fs)" % (time.time() - t0))
    if "compile rc 0" not in pr_.stdout:
        return 1
    lcd = os.path.join(ns.out, "lc", "gen7", "perdef")
    lib = refl.read_mmb(os.path.join(lcd, "perdef.mmb"))
    names1 = {sid: r.terms[oid].name for sid, oid in r.tmap.items()}
    need_names = term_names_of(r.terms, [r.thms[ref] for op, body, kind, ref, line in r.decls if kind == "thm" and line is not None])
    del r
    out_mmb, out_mm0 = os.path.join(ns.out, "out.mmb"), os.path.join(ns.out, "out.mm0")
    r2 = ReflStream(src, lib, names1)
    keep = gen7_names("theorem") | gen7_names("def")
    ndef = r2.open(out_mmb, os.path.join(lcd, "perdef-joined.mm0"), keep, need_names)
    r2.run(ns.max, pubspec)
    fails = [(k, v) for k, v in r2.why.items() if k[0] == "thm"]
    meta = dict(source=os.path.abspath(ns.src), source_sha256=sha256(ns.src), theorems=r2.stats["thms"],
                failed=[(src.thms[k[1]].name, v) for k, v in fails], per_def_lemmas=npd, public_defs=ndef)
    npub = r2.finish(out_mm0, os.path.join(ns.out, "manifest.json"), meta)
    print("pass 2: thms %d failed %d, %d public statements, %d public defs, %d split pieces (%.1fs)" % (
        r2.stats["thms"], len(fails), npub, ndef, r2.nsplit, time.time() - t0))
    with open(out_mm0) as fi:
        rc = subprocess.call([MM0C, out_mmb], stdin=fi)
    print("mm0-c rc", rc, "(%.1fs)" % (time.time() - t0))
    ax = subprocess.call([sys.executable, os.path.join(HERE, "axioms.py"), out_mmb, out_mm0])
    # control: the last public statement with a false conclusion must be rejected
    txt = open(out_mm0).read().rstrip("\n").split("\n")
    k = max(i for i, l in enumerate(txt) if l.startswith("theorem "))
    txt[k] = re.sub(r"\$ [^$]* \$;$", "$ cPr (cNot cTru) $;", txt[k])
    bad = out_mm0 + ".false.mm0"
    open(bad, "w", newline="\n").write("\n".join(txt) + "\n")
    with open(bad) as fi:
        rcb = subprocess.call([MM0C, out_mmb], stdin=fi, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print("false control rc", rcb, "(must be nonzero)")
    return 1 if rc or ax or rcb == 0 or fails else 0


