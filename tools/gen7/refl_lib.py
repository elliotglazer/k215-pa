"""GEN7 C3/C4: production reflection of an .mmb over peano.mm0 into the gen7 output foundation.

  python3 refl_lib.py SRC.mmb OUTDIR [--pub pub|all|none | --roots FILE [--cone]] [--max N]

1. Pass 1 (ReflDry): reflect SRC without proof bodies, to learn the code defs, the per-def
   lemmas the side proofs use and the public statements.
2. OUTDIR/gen7/perdef.mm1: the code defs not already in gen7 and the per-def lemmas
   (nfr_D, nfr_D_j, aeq_D, alpha_D) with proofs generated by perdef.PerDef from L and
   pa-mm0/gen7/gen7_eqv (name-swap equivariance of trPA); imports gen7_lib.mm1.
3. Compile gen7_lib + perdef (lcheck flattening, mm0-rs) -> the output library .mmb.
4. Pass 2 (ReflStream): reflect SRC again over that library, streaming every statement to
   the writer's spool (bounded template cache; statements over the mm0-c heap / store /
   stack limits are split into local lemmas). OUTDIR/out.mmb = library (theorems local
   except gen7's; defs public only where a public statement needs them) + reflection.
   OUTDIR/out.mm0 = peano.mm0 + the gen7 (C1/C2) statements + the needed defs + the public
   reflected statements. OUTDIR/manifest.json lists the reflected roots (public statements),
   renamings, split pieces and mm0-c maxima.
5. Checks: mm0-c out.mmb < out.mm0 (rc 0); the only axioms are peano.mm0's (axioms.py); a
   copy of the spec with the last statement's conclusion falsified is rejected.
"""
