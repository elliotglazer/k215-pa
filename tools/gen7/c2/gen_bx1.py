def tf_self(c, target):
    """c -> target, target = TFg(Eq(v0, t))(t): the left disjunct A. (X <-> X)."""
    need(target[0] == 'or', 'tf_self')
    left = target[1]
    body = left[1]
    need(body[0] == 'and' and body[1][1] == body[1][2] and body[2] == body[1], 'tf_self shape %s' % fm(left))
    a = body[1][1]
    i = ident(c.n + 1, a)
    th = gen(and_intro(i, i))
    return c.app(or_left_ax(c.n, left, target[2]), c.thm(th))

