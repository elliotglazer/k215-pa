_lift_cache = {}
def liftn_thm(th, k):
    """th at level L lifted k levels by the rename rule (shared as lemmas)."""
    key = (th.proof, k)
    if key in _lift_cache: return _lift_cache[key]
    if k == 0: r = th
    else:
        prev = liftn_thm(th, k - 1)
        f2, p = rename_f(0, prev.f)
        r = Thm(prev.n + 1, f2, '(mpbi (paProvableeq2 %s) (g7_lift_rule %s))' % (p, prev.proof))
    _lift_cache[key] = r
    return r

