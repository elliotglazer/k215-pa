"""Generates pa-mm0/gen7/gen7_hle.mm1 (GEN7 C5): PA codes for m <= n and 0 < m at numerals, with completeness
(a true instance is PA-provable). Used, with the T-scheme instances hle / hpos of gen_tsch_inst.py, to discharge
the hypotheses m <= n and 0 < m of the reflected padding lemma inside PA."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gb import *   # noqa

BASE[0] = '(suc 0)'
out = Out()

def at_lemma(name, body, a, b, c, addp, bpr, conv):
    """|- E. body  from the witness num c: body[c] is (s + num c = num b'), proved by addp rewritten by conv."""
    th = ex_intro_imp(0, body, NUM(c))
    inst = th.f[1]
    th = mp(Thm(0, inst, '(mpbir (paProvableeq2 %s) %s)' % (conv, addp)), th)
    out.lemma(name, th, pub=False, binders=' (%s %s: nat)' % (a, c))

out.raw('''-- m <= n and 0 < m as PA codes (one existential: the difference)
@_ def g7LeCode (a b: nat): nat = $ paFormulaEx (paFormulaEqual (paTermAddition (paTermNumeral a) (paTermVariable 0)) (paTermNumeral b)) $;
@_ def g7PosCode (b: nat): nat = $ paFormulaEx (paFormulaEqual (paTermAddition (paTermSuccessor paTermZero) (paTermVariable 0)) (paTermNumeral b)) $;
''')
# a <= a + c
body = Eq(A(NUM('a'), v(0)), NUM('(a + c)'))
at_lemma('g7_le_pa_at', body, 'a', None, 'c', 'paProofNumeralAddition_provable', None, 'eqid')
out.raw('''pub theorem g7_le_pa (a b: nat): $ a <= b -> paProvable 0 (g7LeCode a b) $ =
(named '(eex (mpbid (syl paProvableeq2 (syl g7LeCodeeq2 id)) (a1i g7_le_pa_at))));
''')
# 0 < suc 0 + c
body = Eq(A(S(Z), v(0)), NUM('(suc 0 + c)'))
conv = '(paFormulaEqualeq (paTermAdditioneq (eqcom (eqtr paTermNumeral_succ (paTermSuccessoreq paTermNumeral_zero))) eqid) eqid)'
at_lemma('g7_pos_pa_at', body, 'a', None, 'c', 'paProofNumeralAddition_provable', None, conv)
out.raw('''pub theorem g7_pos_pa (b: nat): $ 0 < b -> paProvable 0 (g7PosCode b) $ =
(named '(eex (mpbid (syl paProvableeq2 (syl g7PosCodeeq id)) (a1i g7_pos_pa_at))));
''')
hdr = '''import "gen7_closed.mm1";

import "../pa_proof_numeral_addition.mm1";

-- G7 C5 (generated by tools/gen7/c2/gen_hle.py): PA codes for m <= n and 0 < m, complete at numerals.
'''
out.write(os.path.join(PA, 'gen7', 'gen7_hle.mm1'), hdr)
print('ok')
