"""Generates pa-mm0/gen7/gen7_l0.mm1 (GEN7 C5): propositional tautologies about CLOSED formulas at level 0
(proved at level 1 by the engine, then lowered with g7_clgen / g7_vac), and the translations of the coded
conjunction / implication under trJ. Used to assemble reflected theorems with hypotheses (hD)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gb import *   # noqa

out = Out()
eng.BOUND_HOOK[0] = None; eng.EQ_HOOK[0] = None
for X in 'ABCD':
    param(X, 'h' + X, 1)
A_, B_, C_, D_ = P0('A'), P0('B'), P0('C'), P0('D')

def last(c, k=0): return c.hyp(len(c.hyps) - 1 - k)
def NA(a, b): return Not(Imp(a, Not(b)))          # the coded conjunction under trJ

def andi(c, fa, fb, a, b):
    c2 = c.push(Imp(a, Not(b)))
    return c.intro(c2.mp(c2.mp(last(c2), fa(c2)), fb(c2)))

def core_and4():
    cx = Ctx(L, [A_, B_, C_, D_])
    x1 = lambda c: andi(c, lambda c: c.hyp(0), lambda c: c.hyp(1), A_, B_)
    X1 = NA(A_, B_)
    x2 = lambda c: andi(c, x1, lambda c: c.hyp(2), X1, C_)
    X2 = NA(X1, C_)
    r = andi(cx, x2, lambda c: c.hyp(3), X2, D_)
    return export(export(export(r)))

def core_iffr():
    cx = Ctx(L, [NA(Imp(A_, B_), Imp(B_, A_))])
    nn = Imp(B_, A_)
    c2 = cx.push(Not(nn))
    c3 = c2.push(Imp(A_, B_))
    f = c2.mp(c2.hyp(0), c2.intro(c3.hyp(1)))
    r = cx.intro(f)
    return cx.app(Thm(L, Imp(Not(Not(nn)), nn), '(bb215D2_dne %s)' % fbound(L, nn)), r)

def core_comp():
    cx = Ctx(L, [Imp(A_, B_), Imp(C_, D_)])
    c2 = cx.push(Imp(B_, C_))
    c3 = c2.push(A_)
    b = c3.mp(c3.hyp(0), last(c3))
    cc = c3.mp(c3.hyp(2), b)
    d = c3.mp(c3.hyp(1), cc)
    return export(cx.intro(c2.intro(d)))

_EQN = {'and': 'And', 'or': 'Or', 'imp': 'Imp', 'all': 'All', 'ex': 'Ex'}
def eqconv(f, hb):
    c = f[0]
    if c == 'par': return '(g7_par_id %s)' % hb[f[1]]
    if c in ('and', 'or', 'imp'): return '(paFormula%seq %s %s)' % (_EQN[c], eqconv(f[1], hb), eqconv(f[2], hb))
    return 'eqid'
def raw(f):
    c = f[0]
    if c == 'par': return f[1]
    if c in ('and', 'or', 'imp'): return '(paFormula%s %s %s)' % (_EQN[c], raw(f[1]), raw(f[2]))
    if c == 'f': return 'paFormulaFalse'
    raise ValueError(c)
def rbound(f, hb):
    c = f[0]
    if c == 'par': return hb[f[1]]
    if c in ('and', 'or', 'imp'): return '(mpbir paFormulaBound_%s (iani %s %s))' % (c, rbound(f[1], hb), rbound(f[2], hb))
    if c == 'f': return 'paFormulaBound_false'
    raise ValueError(c)

def lvl0(name, core, th, params):
    out.lemma(core, th, pub=False, binders=' (n %s: nat) %s' % (' '.join(params), ' '.join('(h%s: $ paFormulaBound (suc n) %s $)' % (x, x) for x in params)))
    hb0 = {x: 'h%s' % x for x in params}
    hb1 = {x: '{(paFormulaBound_mono le01 h%s) : $ paFormulaBound (suc 0) %s $}' % (x, x) for x in params}
    call = '(%s %s)' % (core, ' '.join(hb1[x] for x in params))
    p = '(g7_vac %s (g7_clgen (mpbir (paProvableeq2 %s) %s)))' % (rbound(th.f, hb0), eqconv(th.f, hb1), call)
    out.raw("pub theorem %s (%s: nat) %s:\n  $ paProvable 0 %s $ =\n(named '%s);\n" % (
        name, ' '.join(params), ' '.join('(h%s: $ paFormulaBound 0 %s $)' % (x, x) for x in params), raw(th.f), p))

def core_and2():
    cx = Ctx(L, [A_, B_])
    return export(cx.conj(cx.hyp(0), cx.hyp(1)))
lvl0('g7_and2_0', 'g7l0c_and2', core_and2(), 'AB')
lvl0('g7_and4_0', 'g7l0c_and4', core_and4(), 'ABCD')
lvl0('g7_iffr_0', 'g7l0c_iffr', core_iffr(), 'AB')
lvl0('g7_comp_0', 'g7l0c_comp', core_comp(), 'ABCD')
out.raw('''-- the translation of the coded conjunction and implication under trJ
pub theorem g7_J_cIm (a b: nat): $ trJ (trPA (cIm a b)) = paFormulaImp (trJ (trPA a)) (trJ (trPA b)) $ =
(named '(eqtr g7_tJ_cIm trPA_cIm));
pub theorem g7_J_can (a b: nat): $ trJ (trPA (can a b)) = trNot (paFormulaImp (trJ (trPA a)) (trNot (trJ (trPA b)))) $ =
(named '(eqtr g7_tJ_cNot (eqtr trPA_cNot (trNoteq (eqtr g7_tJ_cIm (eqtr trPA_cIm (paFormulaImpeq eqid (eqtr g7_tJ_cNot trPA_cNot))))))));
''')
hdr = '''import "gen7_ax4.mm1";

-- G7 C5 (generated by tools/gen7/c2/gen_l0.py): level-0 tautologies about closed formulas; trJ of can / cIm.
'''
out.write(os.path.join(PA, 'gen7', 'gen7_l0.mm1'), hdr)
print('ok')
