"""Generates pa-mm0/gen7/gen7_tf2.mm1: trFun X agrees with X when X is a functional total graph."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tg import *   # noqa

BASE[0] = '(suc n)'
L = Lv(1)
param('X', 'hX', 1)
out = Out()
HB = '(n X: nat) (hX: $ paFormulaBound (suc n) X $)'
out.share('g7tf2', HB, ['hX'])

X0 = Par('X', 0, 0)

def TotP(G): return Ex(raise_(G))
def FunP(G): return All(All(Imp(lift(raise_(G)), Imp(raise_(raise_(G)), E10))))

def q1():
    """|- A. v ((X(v) /\\ A. u (X(u) -> u = v)) -> trFun X (v))."""
    xv = raise_(X0)                 # level L+1, slot = v (index 0)
    xu = raise_(raise_(X0))         # level L+2, slot = u (index 0), v = index 1
    uniq = All(Imp(xu, E01))
    tfv = raise_(TF('X'))
    C = Ctx(L + 1, [And(xv, uniq)])
    hx = C.and_left(C.hyp(0)); hu = C.and_right(C.hyp(0))
    left = tfv[1]                   # A. (X(u) <-> u = v)
    body = left[1]                  # level L+2
    C2 = C.lifted()
    hx2 = C2.and_left(C2.hyp(0)); hu2 = C2.and_right(C2.hyp(0))
    # -> : instance of uniq at u (variable 0)
    fwd = C2.app(all_elim_ax(C2.n, hu2.f[2][1], v(0)), hu2)
    # <- : from u = v and X(v): transport X from v (index 1) to u (index 0)
    C3 = C2.push(E01)
    xv3 = C3.and_left(C3.hyp(0))
    hole = raise_(xu)
    xu3 = C3.transport(hole, C3.sym(C3.hyp(1)), xv3)
    bwd = C2.intro(xu3)
    check(fwd.f[2], body[1], 'q1 fwd')
    both = C2.conj(fwd, bwd)
    # generalise over u: C2 is C lifted, so all_intro_hyp
    gen_u = all_intro_hyp(C.n, C.G, Thm(C2.n, Imp(lift(C.G), both.f[2]), both.proof))
    check(gen_u.f[2], left, 'q1 left')
    check(gen_u.f[1], C.G, 'q1 ctx')
    res = C.app(or_left_ax(C.n, left, tfv[2]), gen_u)
    return gen(export_single(res))

def export_single(th):
    """th: (h) -> f with a one-hypothesis context; it already is h -> f."""
    return th

out.lemma('g7_tf_q1', q1(), pub=True, binders=' ' + HB)

def q2():
    """|- (E. w X(w)) -> (A. a A. b (X a -> X b -> a = b)) -> A. v (trFun X (v) -> X(v))."""
    xv = raise_(X0)
    tfv = raise_(TF('X'))
    C = Ctx(L, [TotP(X0), FunP(X0)])
    C0 = C.lifted()
    C1 = C0.push(tfv)
    def left_case(cl):
        inst = cl.app(all_elim_ax(cl.n, cl.hyp(3).f[2][1], v(0)), cl.hyp(3))
        r = cl.mp(cl.and_right(inst), cl.refl(v(0)))
        check(r.f[2], xv, 'q2 left')
        return r
    def right_case(cr):
        neg = cr.and_left(cr.hyp(3))
        E = neg.f[2][1]
        def fn(c2):
            neg2 = c2.and_left(c2.hyp(3))
            body = lift(E)[1]
            target, _ = subst_f(0, v(0), body)        # A. (X(u) <-> u = w), level c2
            c3 = c2.lifted()
            xw = c3.hyp(4)
            iff = target[1]
            xu = iff[1][1]
            c4 = c3.push(xu)
            inst = inst2(c4, c4.hyp(1), v(0), v(1))
            fwd = c3.intro(c4.mp(c4.mp(inst, c4.hyp(5)), c4.hyp(4)))
            c5 = c3.push(iff[2][1])
            bwd = c3.intro(c5.transport(raise_(xu), c5.sym(c5.hyp(5)), c5.hyp(4)))
            both = c3.conj(fwd, bwd)
            check(both.f[2], iff, 'q2 iff')
            allp = all_intro_hyp(c2.n, c2.G, Thm(c3.n, Imp(lift(c2.G), both.f[2]), both.proof))
            wit = c2.witness(body, v(0), allp)
            return c2.mp(neg2, wit)
        r = cr.exists(cr.hyp(0), F, fn)
        return cr.absurd(r, xv)
    res = C1.cases(C1.hyp(2), left_case, right_case)
    imp = C0.intro(res)
    g = all_intro_hyp(C.n, C.G, Thm(C0.n, Imp(lift(C.G), imp.f[2]), imp.proof))
    return export(g)

out.lemma('g7_tf_q2', q2(), pub=True, binders=' ' + HB)

hdr = '''import "gen7_tf.mm1";

-- G7 C2 (generated by tools/gen7/c2/gen_tf2.py): trFun X (v) when v is the unique value of X,
-- and X (v) from trFun X (v) when X is total and functional.
'''
out.write(os.path.join(PA, 'gen7', 'gen7_tf2.mm1'), hdr)
print('ok')
