"""GEN7 C5: the GEN4 wrapper glue (last stage of the staged link): the spec theorems tmPad_haltsPA and tm_run_cut
of targets/g2_generic.mm0 from GEN7's g7_hD and GEN4's tmPad_haltsPA_of_d / tm_run_cut_from_pad.

  python3 mkglue_gen4.py LINKED.mm0 GLUEDIR

LINKED.mm0: the spec of the staged link that proves g7_hD. Writes GLUEDIR/gen7/g7c5_gen4.mm1 / .mm0: imports
g2_generic_tm_defs only; the three used theorems enter as stub axioms (text copied from their proving specs), which
the linker replaces (link R = the g7_hD link + the g2_generic_tm_runcut stage)."""
import os, re, sys
PA = '/home/user/k215-pa-mm0/.claude/worktrees/agent-adc913e38b309817b/pa-mm0'
linked, gd = sys.argv[1], sys.argv[2]

def stmt(path, name):
    s = open(path).read()
    m = re.search(r'(?m)^(?:pub )?theorem %s\b' % re.escape(name), s)
    i = m.start() + (4 if s[m.start():].startswith('pub ') else 0)
    return s[i + len('theorem '):s.index('$;', i) + 1]

spec = open(os.path.join(PA, 'targets', 'g2_generic.mm0')).read()
stubs = [stmt(linked, 'g7_hD'), stmt(os.path.join(PA, 'g2_generic_tm_runcut.mm0'), 'tmPad_haltsPA_of_d'),
         stmt(os.path.join(PA, 'g2_generic_tm_runcut.mm0'), 'tm_run_cut_from_pad')]
T1, T2 = stmt(os.path.join(PA, 'targets', 'g2_generic.mm0'), 'tmPad_haltsPA'), stmt(os.path.join(PA, 'targets', 'g2_generic.mm0'), 'tm_run_cut')
body1 = ''.join('axiom %s;\n\n' % x for x in stubs)
p1 = "pub theorem %s =\n(named '(tmPad_haltsPA_of_d (ax_gen g7_hD) hM hp h0 hmn));\n\n" % T1
p2 = "pub theorem %s =\n(named '(tm_run_cut_from_pad hM hmn (ax_gen g7_hD)));\n" % T2
hdr = '-- SCRATCH (staged link, last stage): GEN4 spec theorems from g7_hD; generated by tools/gen7/c2/mkglue_gen4.py.\n'
open(os.path.join(gd, 'gen7', 'g7c5_gen4.mm1'), 'w').write('import "../g2_generic_tm_defs.mm1";\n\n' + hdr + body1 + p1 + p2)
open(os.path.join(gd, 'gen7', 'g7c5_gen4.mm0'), 'w').write('import "../g2_generic_tm_defs.mm0";\n\n' + hdr + body1 +
    'theorem %s;\n\ntheorem %s;\n' % (T1, T2))
print('ok')
