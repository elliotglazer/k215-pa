r"""GEN7 C5: source of the reflection for reflThInconsistent_pr (set and PA front ends), "inconsistency adequacy".

  python3 gen_incsrc.py

Writes
  pa-mm0/g7_incsrc.mm1 / .mm0       HOST source: d3_adqsrc (route T's reflection source) + GEN2's set-front-end
                                    defines closure + the two theorems below; reflect it with
                                    tools/gen7/c2/roots_inc.txt (= route T's roots_adq.txt + g7r_painc + g7r_sfinc).
  pa-mm0/gen7/g7_incsrc_t.mm1 / .mm0  TEST ONLY local source: d3_rsrc2 (route T's local stand-ins) + the same closure
                                    for the set side, with GEN3's g2paAxSet / g2paThCode_defines as stand-ins.

The two theorems (implication form; the hypothesis hR of GEN2's / GEN3's defines theorems is discharged by an
if-substitution on R, as in d3_adqsrc's d3r_adq, so that their reflections have no side hypotheses):
  g7r_painc (R S): paFormulaBound 1 R /\ paS1Class 1 R -> R = S -> paS1Holds (g2paThCode R) (paFormulaFalse : 0) ->
                   paThProvable (g2paAxSet S) paFormulaFalse                          (GEN3 g2paThCode_defines)
  g7r_sfinc (R S): paFormulaBound 1 R /\ paS1Class 1 R -> R = S -> paS1Holds (g2sfThCodeL R) (sfBot : 0) ->
                   sfTheoryProvable (g2sfAxSet S) sfBot                               (GEN2 g2sfThCodeL_defines)
The conclusions are the bodies of the spec's paThInconsistent R / sfThInconsistent R with the abstract
paSigma1True replaced by paS1Holds (GEN3's / GEN2's literal axiom sets)."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
PA = os.path.join(ROOT, 'pa-mm0')

H = "paFormulaBound 1 R /\\ paS1Class 1 R"
IFR = "(if (%s) R paFormulaFalse)" % H
THMS = r'''
theorem g7r_h (R: nat): $ paFormulaBound 1 IFR /\ paS1Class 1 IFR $ =
'(cases (mpbird (aneqd (paFormulaBoundeqd (a1i eqid) ifpos) (paS1Classeqd (a1i eqid) ifpos)) id)
  (mpbird (aneqd (paFormulaBoundeqd (a1i eqid) ifneg) (paS1Classeqd (a1i eqid) ifneg)) (a1i (iani paFormulaBound_false paS1Class_false))));

#PA
pub theorem g7r_painc (R S: nat): $ HR -> R = S -> paS1Holds (g2paThCode R) (paFormulaFalse : 0) ->
  paThProvable (g2paAxSet S) paFormulaFalse $ =
'(exp (syld (bi2d (paS1Holdseqd (g2paThCodeeqd (syl ifpos anl)) (a1i eqid)))
  (syld (a1i (bi1i (g2paThCode_defines g7r_h)))
    (bi1d (paThProvableeqd (g2paAxSeteqd (eqtrd (syl ifpos anl) anr)) (a1i eqid))))));

#SF
pub theorem g7r_sfinc (R S: nat): $ HR -> R = S -> paS1Holds (g2sfThCodeL R) (sfBot : 0) ->
  sfTheoryProvable (g2sfAxSet S) sfBot $ =
'(exp (syld (bi2d (paS1Holdseqd (g2sfThCodeLeqd (syl ifpos anl)) (a1i eqid)))
  (syld (a1i (bi1i (g2sfThCodeL_defines g7r_h)))
    (bi1d (sfTheoryProvableeqd (g2sfAxSeteqd (eqtrd (syl ifpos anl) anr)) (a1i eqid))))));
'''.replace('IFR', IFR).replace('HR', H)
STMTS = '''
theorem g7r_painc (R S: nat): $ HR -> R = S -> paS1Holds (g2paThCode R) (paFormulaFalse : 0) ->
  paThProvable (g2paAxSet S) paFormulaFalse $;

theorem g7r_sfinc (R S: nat): $ HR -> R = S -> paS1Holds (g2sfThCodeL R) (sfBot : 0) ->
  sfTheoryProvable (g2sfAxSet S) sfBot $;
'''.replace('HR', H)
FIN = "\npub theorem %s_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;\n"
FIN0 = "\ntheorem %s_final: $ paFormulaBound 0 paFormulaFalse $;\n"
HDR = '-- GEN7 C5 (generated by tools/gen7/c2/gen_incsrc.py): inconsistency adequacy for reflThInconsistent_pr(_pa).\n'
TH_H, rest = THMS.split('#PA')
TH_PA, TH_SF = rest.split('#SF')
THMS = TH_H + TH_PA + TH_SF
# TEST ONLY: refl_lib cannot reflect a source axiom, so the local test leaves g7r_painc out (its reflection
# g7r_painc_R is a kept axiom of the local link, as route T's d3r_adq_R); g7t_root makes the local reflection emit
# the code defs of its conclusion.
STAND = r'''-- TEST ONLY stand-in: GEN3's g2paAxSet (as in GEN3's .mm0); g7t_root forces its code defs.
@_ def g2paAxSet (R .a: nat): set = $ {a | paFormulaBound 0 a /\ paS1Holds R (a : 0)} $;
pub theorem g7t_root (S: nat): $ paThProvable (g2paAxSet S) paFormulaFalse -> paThProvable (g2paAxSet S) paFormulaFalse $ = 'id;
'''
STAND0 = STAND.replace('@_ def', 'def').replace(" = 'id;", ";").replace('pub theorem', 'theorem')
STMTS_SF = STMTS.split('theorem g7r_sfinc')[1]


def main():
    imp1 = ['d3_adqsrc', 'g2_generic_sf_defines', 'g2_generic_tm_defs']
    w = lambda p, s: open(os.path.join(PA, p), 'w').write(s)
    w('g7_incsrc.mm1', ''.join('import "%s.mm1";\n' % i for i in imp1) + '\n' + HDR + THMS + "\n-- the code def ctmHalts of the halting predicate (reflTmHalts' draft body) in the same reflection\npub theorem g7r_tmh (k M: nat): $ tmHalts k M -> tmHalts k M $ = 'id;\n" + FIN % 'g7_incsrc')
    w('g7_incsrc.mm0', ''.join('import "%s.mm0";\n' % i for i in imp1) + '\n' + HDR + STMTS + "\ntheorem g7r_tmh (k M: nat): $ tmHalts k M -> tmHalts k M $;\n" + FIN0 % 'g7_incsrc')
    # TEST ONLY: route T's local stand-ins d3_s6defs / d3_s6ql, minus the defs that GEN2's closure (s1_tbase) declares
    tb = set(re.findall(r'(?m)^(?:@_ )?def (\S+)', open(os.path.join(PA, 'g2_generic_s1_tbase.mm1')).read()))
    for ext in ('mm1', 'mm0'):
        src = open(os.path.join(PA, 'gen7', 'd3_s6defs.' + ext)).read()
        keep = [l for l in src.split('\n') if not (re.match(r'(?:@_ )?def (\S+)', l) and re.match(r'(?:@_ )?def (\S+)', l).group(1) in tb)]
        t = '\n'.join(keep).replace('d3s6_root', 'g7s6t_root').replace('d3_s6defs_final', 'g7_s6defs_t_final')
        t = t.replace('import "../g2_generic_s1_class.%s";' % ext, 'import "../g2_generic_s1_class.%s";\nimport "../g2_generic_s1_tbase.%s";' % (ext, ext))
        w('gen7/g7_s6defs_t.' + ext, '-- TEST ONLY (generated by tools/gen7/c2/gen_incsrc.py from d3_s6defs).\n' + t)
        q = open(os.path.join(PA, 'gen7', 'd3_s6ql.' + ext)).read().replace('d3_s6defs.', 'g7_s6defs_t.').replace('d3_s6ql_final', 'g7_s6ql_t_final')
        w('gen7/g7_s6ql_t.' + ext, '-- TEST ONLY (generated by tools/gen7/c2/gen_incsrc.py from d3_s6ql).\n' + q)
    imp2 = ['d3_rsrc', 'g7_s6ql_t', '../g2_generic_sf_defines', '../g2_generic_pa_rules', '../g2_generic_tm_defs']
    w('gen7/g7_incsrc_t.mm1', ''.join('import "%s.mm1";\n' % i for i in imp2) + '\n' + HDR + STAND + TH_H + TH_SF + "\n-- the code def ctmHalts of the halting predicate (reflTmHalts' draft body) in the same reflection\npub theorem g7r_tmh (k M: nat): $ tmHalts k M -> tmHalts k M $ = 'id;\n" + FIN % 'g7_incsrc_t')
    w('gen7/g7_incsrc_t.mm0', ''.join('import "%s.mm0";\n' % i for i in imp2) + '\n' + HDR + STAND0 + '\ntheorem g7r_sfinc' + STMTS_SF + "\ntheorem g7r_tmh (k M: nat): $ tmHalts k M -> tmHalts k M $;\n" + FIN0 % 'g7_incsrc_t')
    open(os.path.join(HERE, 'roots_inc.txt'), 'w').write(
        open(os.path.join(ROOT, 'tools', 'gen7', 'd3', 'roots_adq.txt')).read().rstrip('\n') + '\ng7r_painc\ng7r_sfinc\ng7r_tmh\n')
    open(os.path.join(HERE, 'roots_inc_t.txt'), 'w').write(
        open(os.path.join(ROOT, 'tools', 'gen7', 'd3', 'roots_m.txt')).read().rstrip('\n') + '\nd3r_ql\ng7s6t_root\ng7t_root\ng7r_sfinc\ng7r_tmh\n')
    print('ok')


main()
