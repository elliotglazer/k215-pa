"""GEN7 C5: S6 for the set front end (route T's gen_s6.py method applied to GEN2's g2sfThCodeL).

  python3 gen_s6sf.py

Writes pa-mm0/gen7/g7_s6sf.mm1 / .mm0: for every def D of g2sfThCodeL's closure (GEN2, g2_generic_sf_code.mm0)
  d3s6_D (p..): cD (r p) .. = r (D p ..)       (META equality, unfolding + d3r / d3rt equations; tools/gen7/d3/gen_s6.py)
and
  g7_S6sf (R): cPr (cEq (cg2sfThCodeL (d3r R)) (d3r (g2sfThCodeL R)))
(no side conditions: g2sfThCodeL has no bound wrappers)."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'gen7', 'd3'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'gen7'))
import gen_s6 as G   # noqa: E402

PA = os.path.join(ROOT, 'pa-mm0')
ROOTDEF = 'g2sfThCodeL'


def main():
    defs, texts = {}, {}
    import tempfile, shutil
    d = tempfile.mkdtemp()
    try:
        L = {'__file__': os.path.join(ROOT, 'tools', 'gen7', 'lcheck.py'), '__name__': 'lcheck'}
        exec(open(L['__file__']).read().replace('\nmain()', '\n'), L)
        m0 = []
        L['closure']('g2_generic_sf_code.mm0', m0, set())
        for i, (rel, pth, txt) in enumerate(m0):
            open(os.path.join(d, '%04d.mm0' % i), 'w').write(txt)
        defs, texts = G.load(d)
    finally:
        shutil.rmtree(d)
    for k in G.CON:
        defs.pop(k, None)
    order = G.closure(defs, [ROOTDEF])
    dsort, psort = G.infer(defs, order)
    nums = set()
    for x in order:
        G.heads(defs[x][1], nums)
    kmax = max([int(x) for x in nums if re.fullmatch(r'\d+', x)] + [8])
    out = ['import "d3_s5.mm1";', 'import "../g2_generic_sf_code.mm1";', '',
           '-- GEN7 C5 (generated by tools/gen7/c2/gen_s6sf.py): S6 for the set front end, normal forms of the code of',
           '-- g2sfThCodeL R (route T method, tools/gen7/d3/gen_s6.py).', 'do {']
    for x in order:
        out.append("  (if (def? (get-decl 'c%seqd)) () (default-annotate 'c%s))" % (x, x))  # guarded: d3_s3h annotates the shared cg2s1* too
    out.append('};')
    for k in range(9, kmax + 1):
        prev = 'd3e_cn8' if k == 9 else 'g7e_cn%d' % (k - 1)
        out.append("theorem g7e_cn%d: $ d3cn %d = cd%d $ = '(eqtr d3cn_S (cSuceq %s));" % (k, k, k, prev))
    fix = lambda s: re.sub(r'd3e_cn(\d+)', lambda m: ('g7e_cn' if int(m.group(1)) >= 9 else 'd3e_cn') + m.group(1), s).replace('d3s6_', 'g7s6_')
    for x in order:
        vs = defs[x][0]
        bind = ' (%s: nat)' % ' '.join(vs) if vs else ''
        lhs = 'c%s%s' % (x, ''.join(' (%s %s)' % (G.RR[psort[x].get(v, 'F')], v) for v in vs)) if vs else 'c' + x
        rhs = '%s %s' % (G.RR[dsort[x]], '(%s %s)' % (x, ' '.join(vs)) if vs else x)
        out.append("theorem g7s6_%s%s: $ %s = %s $ =\n'%s;" % (x, bind, lhs, rhs, fix(G.proof(defs[x][1], x, defs, dsort, psort, dsort[x]))))
    out.append("pub theorem g7_S6sf (R: nat): $ cPr (cEq (cg2sfThCodeL (d3r R)) (d3r (g2sfThCodeL R))) $ =\n"
               "'(mpbir (cPreq (cEqeq g7s6_g2sfThCodeL eqid)) d3r_eqid_R);")
    out.append("pub theorem g7_s6sf_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;")
    p = os.path.join(PA, 'gen7', 'g7_s6sf.mm1')
    open(p, 'w').write('\n'.join(out) + '\n')
    print('defs', order, 'bytes', os.path.getsize(p))


main()
