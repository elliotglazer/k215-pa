"""GEN7 C5: the slim base of a glue module for the staged link (tools/gen7/link.py on branch d3-route).

  python3 mkslim.py GLUEDIR NAME:FILE[,NAME:FILE..]

Writes GLUEDIR/gen7/g7c5_slim.mm1 / .mm0: imports of small modules only, the code defs of the reflection
(GLUEDIR/gen7/perdef.mm0) and of the gen7 library modules not imported, the defs of the T-scheme instances, and
STUB axioms (statement text copied from the module that proves them) for every theorem the glue uses from a
module it does not import. The linker replaces each stub by the theorem of that name (mm0-c rejects a stub
whose text differs), so the glue compiles without the large instance modules in its closure.
"""
import os, re, sys
PA = '/home/user/k215-pa-mm0/.claude/worktrees/agent-adc913e38b309817b/pa-mm0'
gd, wants = sys.argv[1], sys.argv[2].split(',')
IMPORTS = ['gen7_num', 'gen7_l0', 'gen7_hle', '../g2_generic_tm_defs', '../g2_generic_bbsem_table_arithmetic_valid_code']
LIBDEFS = [('gen7_bx1', 'cex'), ('gen7_bx3', 'csb'), ('gen7_bx5', 'ceqs')]
INSTDEFS = [('gen7_tmh', 'g7tmhCode'), ('gen7_tval', 'g7tvalCode'), ('gen7_tpad', 'g7tpadCode'),
            ('gen7_tpad', 'g7PadFullCode'), ('gen7_thle', 'g7hleCode'), ('gen7_thpos', 'g7hposCode')]

def defline(path, name):
    s = open(path).read()
    i = s.index('\ndef %s ' % name) + 1
    return s[i:s.index('$;', i) + 2]

def stmt(path, name):
    """the statement 'NAME binders: $ .. $' of theorem NAME in a .mm0 or .mm1 file."""
    s = open(path).read()
    m = re.search(r'(?m)^(?:pub )?theorem %s\b' % re.escape(name), s)
    i = m.start() + (4 if s[m.start():].startswith('pub ') else 0)
    cands = [x for x in (s.find('$;', i), (lambda m2: m2.start() if m2 else -1)(re.compile(r'\$\s*=').search(s, i))) if x >= 0]
    e = min(cands)
    return s[i + len('theorem '):e + 1]

out = []
for f, n in LIBDEFS:
    out.append(defline(os.path.join(PA, 'gen7', f + '.mm0'), n))
pd = open(os.path.join(gd, 'gen7', 'perdef.mm0')).read()
out += re.findall(r'(?ms)^def .*?\$;', pd)
for f, n in INSTDEFS:
    out.append(defline(os.path.join(PA, 'gen7', f + '.mm0'), n))
for w in wants:
    n, f = w.split(':')
    p = f if f.startswith('/') else os.path.join(PA, f)
    out.append('axiom ' + stmt(p, n) + ';')
body = '\n\n'.join(out) + '\n'
hdr = '-- SCRATCH (staged link): defs and stub axioms, generated by tools/gen7/c2/mkslim.py.\n'
for ext in ('mm1', 'mm0'):
    open(os.path.join(gd, 'gen7', 'g7c5_slim.' + ext), 'w').write(
        ''.join('import "%s.%s";\n\n' % (i, ext) for i in IMPORTS) + hdr + body)
print(len(out), 'items')
