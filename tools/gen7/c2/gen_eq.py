def ax7_core():
    """|- Fun A -> EQ A B -> EQ A C -> EQ B C."""
    eqab, eqac, eqbc = EQ('A', 'B'), EQ('A', 'C'), EQ('B', 'C')
    C1 = Ctx(L, [Fun('A'), eqab, eqac])
    def fn1(c2):
        def fn2(c3):
            fun = c3.hyp(0)
            inst = inst2(c3, fun, v(1), v(0))
            hu, hw = c3.hyp(3), c3.hyp(4)
            ha_u, hb_u = c3.and_left(hu), c3.and_right(hu)
            ha_w, hc_w = c3.and_left(hw), c3.and_right(hw)
            check(inst.f[2][1], ha_u.f[2], 'ax7 fun u')
            eq_uw = c3.mp(c3.mp(inst, ha_u), ha_w)
            hole = raise_(hc_w.f[2])
            hc_u = c3.transport(hole, c3.sym(eq_uw), hc_w)
            r = c3.conj(hb_u, hc_u)
            goal3 = lift(lift(eqbc))
            return c3.witness(goal3[1], v(1), r)
        return c2.exists(c2.hyp(2), lift(eqbc), fn2)
    g = C1.exists(C1.hyp(1), eqbc, fn1)
    # discharge: C1.G = (Fun /\ eqab) /\ eqac
    return export(export(g))

th = ax7_core()
out.lemma('g7_eq_ax7', mp(Thm(L, Fun('A'), '(g7_tf_fun hA)'), th), pub=True,
          binders=' ' + HBIND)

def ax8_core():
    """|- Fun A -> EQ A B -> EL A S -> EL B S."""
    eqab, elas, elbs = EQ('A', 'B'), EL('A', 'S'), EL('B', 'S')
    C1 = Ctx(L, [Fun('A'), eqab, elas])
    def fn1(c2):
        def fn2(c3):
            inst = inst2(c3, c3.hyp(0), v(1), v(0))
            hu, hw = c3.hyp(3), c3.hyp(4)
            ha_u, hb_u = c3.and_left(hu), c3.and_right(hu)
            ha_w, hs_w = c3.and_left(hw), c3.and_right(hw)
            eq_uw = c3.mp(c3.mp(inst, ha_u), ha_w)
            hs_u = c3.transport(raise_(hs_w.f[2]), c3.sym(eq_uw), hs_w)
            r = c3.conj(hb_u, hs_u)
            return c3.witness(lift(lift(elbs))[1], v(1), r)
        return c2.exists(c2.hyp(2), lift(elbs), fn2)
    return export(export(C1.exists(C1.hyp(1), elbs, fn1)))

out.lemma('g7_eq_ax8', mp(Thm(L, Fun('A'), '(g7_tf_fun hA)'), ax8_core()), pub=True, binders=' ' + HBIND)

