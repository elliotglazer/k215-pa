"""Generates pa-mm0/gen7/gen7_ax6.mm1: coded addeq, muleq of L."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ga import *   # noqa

out = Out()
out.share('g7a6', HB, ['h' + x for x in NAMES])
Facts.PFX[0] = 'g7f6'
eng.BOUND_MIN = 2000

A_, B_, C_, D_ = ('A',), ('B',), ('C',), ('D',)

def opeq_core(op):
    """EQ(A,B) -> EQ(C,D) -> EQg(A op C, B op D)."""
    spL = (op, A_, C_); spR = (op, B_, D_)
    fx = Facts(out); fx.need(spL); fx.need(spR)
    goal = EQg(build(spL), build(spR))
    C = fx.ctx([EQ('A', 'B'), EQ('C', 'D')])
    mk = A if op == '+' else M
    def fu(c2):                                        # u v0
        def fw(c3):                                    # u v1, w v0
            def fs(c4):                                # u v2, w v1, s v0
                hab = c4.hyp(2); hcd = c4.hyp(3); es = c4.hyp(4)
                gl = mk_gop(c4, build(spL), 0, c4.and_left(hab), 2, c4.and_left(hcd), 1, es)
                gr = mk_gop(c4, build(spR), 0, c4.and_right(hab), 2, c4.and_right(hcd), 1, es)
                tfl = tf_in(c4, fx, spL, gl)
                tfr = tf_in(c4, fx, spR, gr)
                return c4.witness(liftn(goal, 3)[1], v(0), c4.conj(tfl, tfr))
            return c3.exists(name_term(c3, mk(v(1), v(0))), liftn(goal, 2), fs)
        return c2.exists(c2.hyp(1), lift(goal), fw)
    return fx.discharge(C.exists(C.hyp(0), goal, fu), 2)

LTS = ['(lttr cArg1_lt cArg1_lt)', '(lttr cArg2_lt cArg1_lt)',
       '(lttr cArg1_lt (lttr cArg1_lt cArg2_lt))', '(lttr cArg2_lt (lttr cArg1_lt cArg2_lt))']
H = ' '.join('(g7_trb_lt %s)' % lt for lt in LTS)

for name, op, cop in (('addeq', '+', 'cAdd'), ('muleq', '*', 'cMul')):
    core = opeq_core(op)
    out.lemma('g7_%s_core' % name, core, pub=True, binders=' ' + HB)
    spL = (op, A_, C_); spR = (op, B_, D_)
    off, E, p = conv_EQ(spL, spR)
    check(core.f[2][2], E, name + ' core form')
    out.thm('g7_%s_conv %s' % (name, HB), '%s = %s' % (off, fm(E)), p, pub=True)
    hs = ['(g7_trb_lt %s)' % lt for lt in LTS]
    E1 = '(eqtr g7_tJ_cEq (eqtr trPA_cEq (g7_EQ_E %s %s)))' % (hs[0], hs[1])
    E2 = '(eqtr g7_tJ_cEq (eqtr trPA_cEq (g7_EQ_E %s %s)))' % (hs[2], hs[3])
    E3 = '(eqtr g7_tJ_cEq (eqtr trPA_cEq (eqtr (trEqFeq %s %s) (g7_%s_conv hA hB hC hD))))' % (
        code_eq(spL), code_eq(spR), name)
    TOP = '(eqtr trPA_cIm (paFormulaImpeq %s (eqtr g7_tJ_cIm (eqtr trPA_cIm (paFormulaImpeq %s %s)))))' % (E1, E2, E3)
    out.raw('''pub theorem %s_R (v0: nat) (v1: nat) (v2: nat) (v3: nat): $ cPr (cIm (cEq v0 v1) (cIm (cEq v2 v3) (cEq (%s v0 v2) (%s v1 v3)))) $ =
(named '(bi2 (g7_cpr_iff g7_tr_bound) (mpbir (paProvableeq2 %s) (g7_%s_core %s))));
''' % (name, cop, cop, TOP.replace('hA hB hC hD', H), name, H))

hdr = '''import "gen7_ax4.mm1";

-- G7 C2 (generated by tools/gen7/c2/gen_ax6.py): coded addeq, muleq.
'''
out.write(os.path.join(PA, 'gen7', 'gen7_ax6.mm1'), hdr)
print('ok')
