"""GEN7 C5 glue (hand side of the linker step) for a T-scheme instance of gen_tsch_inst.py.

  python3 mkglue.py CONFIG OUT.mm0 GLUEDIR

OUT.mm0 / GLUEDIR: a refl_lib output (run with GEN7_NEED=pf:<rhs code def>) of the source theorem SRC_flat.
Writes GLUEDIR/gen7/g7c5_glue_CONFIG.mm1 (the glue lemmas over perdef.mm1 and the instance module; the
reflected statement enters as hypothesis hR) and GLUEDIR/gen7/g7c5_gluetest_CONFIG.mm1 / .mm0 (SCRATCH
test: the reflected statement as a stub axiom, applied at numeral codes; this is the step the linker splices).
"""
import os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))), 'pa-mm0'))
import bb215_l3_engine as eng
CONFIGS = {
    'tmh': dict(args=['k', 'M'], code='g7tmhCode', thm='g7_tmh', module='gen7_tmh', src='g7src_tmh_flat_R',
                rcode='ctmHalts', glue=[
        ('g7_reflTmHalts_code_of', '', 'paProvable 0 (paFormulaImp (trJ (trPA (ctmHalts (cNum k) (cNum M)))) (tmHaltsPA k M))',
         "(g7_tmh_bridge hR FR)")]),
    'tval': dict(args=['nst', 'T'], code='g7tvalCode', thm='g7_tval', module='gen7_tval', src='g7src_tval_flat_R',
                 rcode='ctmValid', glue=[
        ('g7_hc_tmValid_of', '(hv: $ paProvable 0 (paFormulaSubst 0 (paTermNumeral T) (tmgTableArithmeticValidCode nst)) $)', 'paProvable 0 (trJ (trPA (ctmValid (cNum nst) (cNum T))))',
         "(bb215D2_mp hv (g7_tval_bridge_rev hR FR))")]),
}
cfg = CONFIGS[sys.argv[1]]
spec, gd = sys.argv[2], sys.argv[3]
s = open(spec).read()
i = s.index('theorem %s ' % cfg['src'])
j = s.index('$;', s.index('$ cPr', i)) + 2
stmt = s[i:j]
hyps = re.findall(r'\(h(\d+): \$ (nfr|nne) v(\d+) v(\d+) \$\)', stmt)
na = len(cfg['args'])
nv = len(re.findall(r'\(v\d+: nat\)', stmt))
side = []
for h, kind, a, b in hyps:
    a, b = int(a), int(b)
    if kind == 'nfr':
        assert b < na and a >= na
        side.append('nfr_cNum')
    else:
        x, y = a - na, b - na
        assert x != y and x >= 0 and y >= 0
        side.append('(ltnei %s)' % eng.lt(x, y) if x < y else '(ltneri %s)' % eng.lt(y, x))
VS = ' '.join(cfg['args'])
nums = ' '.join('(cNum %s)' % a for a in cfg['args'])
FR = '(g7pfc_%s %s)' % (cfg['rcode'], ' '.join(['(g7_nfr_fresh nfr_cNum)'] * na))
HR = 'cPr (ciff (%s %s) (%s %s))' % (cfg['code'], VS, cfg['rcode'], nums)
items = ['import "perdef.mm1";\n', 'import "%s.mm1";\n' % cfg['module']] + ['import "%s.mm1";\n' % m for m in cfg.get('imports', [])] + [
         '-- G7 C5 glue (generated by tools/gen7/c2/mkglue.py %s): the reflected flat adequacy at numeral codes enters as hR.\n' % sys.argv[1]]
for name, extra, concl, proof in cfg['glue']:
    items.append("pub theorem %s (%s: nat) {x: nat} %s\n  (hR: $ %s $):\n  $ %s $ =\n(named '%s);\n"
                 % (name, VS, extra, HR, concl, proof.replace('FR', FR)))
open(gd + '/gen7/g7c5_glue_%s.mm1' % sys.argv[1], 'w').write('\n'.join(items))
m0 = ['import "perdef.mm0";\n', 'import "%s.mm0";\n' % cfg['module']] + ['import "%s.mm0";\n' % m for m in cfg.get('imports', [])]
for name, extra, concl, proof in cfg['glue']:
    m0.append("theorem %s (%s: nat) {x: nat} %s\n  (hR: $ %s $):\n  $ %s $;\n" % (name, VS, extra, HR, concl))
open(gd + '/gen7/g7c5_glue_%s.mm0' % sys.argv[1], 'w').write('\n'.join(m0))
# scratch stub test
args = ' '.join(['(cNum %s)' % a for a in cfg['args']] + [eng.num(d) for d in range(nv - na)])
tl1, tl0 = [], []
for name, extra, concl, proof in cfg['glue']:
    hv = ' hv' if extra else ''
    tl1.append("pub theorem %s_test (%s: nat) %s:\n  $ %s $ =\n(named '(%s%s (%s %s)));\n" % (name, VS, extra, concl, name, hv, cfg['src'], ' '.join(side)))
    tl0.append("theorem %s_test (%s: nat) %s:\n  $ %s $;\n" % (name, VS, extra, concl))
if sys.argv[1] == 'tmh':
    # the spec statement of targets/g2_generic.mm0 (F) under the DRAFT literal body (pa-mm0/gen7/refl_bodies.draft.mm0)
    D = 'def reflTmHalts (k M: nat): nat = $ trJ (trPA (ctmHalts (cNum k) (cNum M))) $;\n'
    S = 'reflTmHalts_code (k M: nat):\n  $ paProvable 0 (paFormulaImp (reflTmHalts k M) (tmHaltsPA k M)) $'
    tl1.append(D + "pub theorem %s =\n(named 'g7_reflTmHalts_code_of_test);\n" % S)
    tl0.append(D + "theorem %s;\n" % S)
ax = 'axiom ' + stmt[len('theorem '):]
open(gd + '/gen7/g7c5_gluetest_%s.mm1' % sys.argv[1], 'w').write(
    'import "g7c5_glue_%s.mm1";\n\n-- SCRATCH ONLY: the reflected statement as a stub axiom (it is a theorem of out.mmb).\n%s\n\n%s'
    % (sys.argv[1], ax, '\n'.join(tl1)))
open(gd + '/gen7/g7c5_gluetest_%s.mm0' % sys.argv[1], 'w').write('import "g7c5_glue_%s.mm0";\n\n%s\n\n%s' % (sys.argv[1], ax, '\n'.join(tl0)))
print(len(side), 'side proofs', nv, 'vars')
if sys.argv[1] == 'tmh':
    # G2GEN 2026-11-02: the real (non-scratch) tmh glue for g7_incH. The reflected g7src_tmh_flat_R enters as a STUB
    # axiom copied verbatim from the reflection's out.mm0; link.py maps it to the reflection's theorem of the same name
    # (local: the reflection of g7src_tmh; host: of d3_adqsrcS, which contains g7src_tmh and has g7src_tmh_flat among its
    # roots). The reflection must be run with GEN7_NEED containing pf:ctmHalts (g7pfc_ctmHalts in its perdef).
    hd = ('-- G2GEN / GEN7 C5 (generated by tools/gen7/c2/mkglue.py tmh): reflTmHalts_code at the draft literal body, from the\n'
          '-- reflected flat adequacy g7src_tmh_flat_R (stub below, verbatim from the reflection; resolved by link.py).\n')
    L = 'g7_reflTmHalts_codeL (k M: nat): $ paProvable 0 (paFormulaImp (trJ (trPA (ctmHalts (cNum k) (cNum M)))) (tmHaltsPA k M)) $'
    open(gd + '/gen7/g7_tmhglue.mm1', 'w').write(
        'import "g7c5_glue_tmh.mm1";\n\n%s\n%s\n\npub theorem %s =\n(named \'(g7_reflTmHalts_code_of (%s %s)));\n'
        % (hd, ax, L, cfg['src'], ' '.join(side)))
    open(gd + '/gen7/g7_tmhglue.mm0', 'w').write('import "g7c5_glue_tmh.mm0";\n\n%s\n\ntheorem %s;\n' % (ax, L))
