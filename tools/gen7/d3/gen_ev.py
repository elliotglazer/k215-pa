"""Route T: generates pa-mm0/gen7/d3_ev.mm1 (EV lemmas: coded meta rules, numerals, term bounds, env, UT, freshness).
  python3 gen_ev.py RM/out.mm0
Stub axioms are copied verbatim from the master reflection RM (tools/gen7/d3/rm.sh) for the roots in roots_m.txt."""
import os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, HERE)
import ded
from ded import wrapper
ded.ANNOT = True

E = '(cEq c0 c0)'
items = []
def add(name, binders, hyps, concl, primed, dflt, call):
    items.append('pub ' + wrapper(name, binders, hyps, concl, primed, dflt, call))

# coded modus ponens and generalization, implication form
add('d3_cmp', '(a b: nat)', ['cPr (cIm a b)', 'cPr a'], 'cPr b', [('a', E), ('b', E)],
    ['(ax_mp_R ax_1_R d3r_eqid_R)', 'd3r_eqid_R'], '(ax_mp_R {h0} {h1})')
add('d3_cgen', '(x a: nat)', ['cPr a'], 'cPr (cAl x a)', [('a', E)], ['d3r_eqid_R'], '(ax_gen_R {h0})')
# freshness through the structural constructors
for nm, head, n in (('d3_nfS', 'cpaTermSuccessor', 1), ('d3_nfA', 'cpaTermAddition', 2), ('d3_nfM', 'cpaTermMultiplication', 2),
                    ('d3_nfE', 'cpaFormulaEqual', 2), ('d3_nfAnd', 'cpaFormulaAnd', 2), ('d3_nfOr', 'cpaFormulaOr', 2),
                    ('d3_nfImp', 'cpaFormulaImp', 2), ('d3_nfAll', 'cpaFormulaAll', 1), ('d3_nfEx', 'cpaFormulaEx', 1),
                    ('d3_nfcons', 'ccons', 2), ('d3_nfTV', 'cbb215ArithmeticFormulaTermValue', 2), ('d3_nfEnv', 'cpaS1Env', 1)):
    vs = ['a', 'b'][:n]
    add(nm, '(x %s: nat)' % ' '.join(vs), ['nfr x %s' % v for v in vs], 'nfr x (%s %s)' % (head, ' '.join(vs)),
        [(v, 'c0') for v in vs], ['nfr_c0'] * n, '(nfr_%s %s)' % (head, ' '.join('{h%d}' % i for i in range(n))))
# reflected laws with freshness side conditions
def stubw(name, stub, vs, concl):
    add(name, '(%s x: nat)' % ' '.join(vs), ['nfr x %s' % v for v in vs], concl, [(v, 'c0') for v in vs], ['nfr_c0'] * len(vs),
        '(%s %s)' % (stub, ' '.join('{h%d}' % i for i in range(len(vs)))))
stubw('d3_Hex', 'paS1Holds_ex_R', ['a', 'e'],
      'cPr (ciff (cpaS1Holds (cpaFormulaEx a) e) (cex x (cpaS1Holds a (ccons (cV x) e))))')
stubw('d3_Fal', 'paS1Fails_all_R', ['a', 'e'],
      'cPr (ciff (cpaS1Fails (cpaFormulaAll a) e) (cex x (cpaS1Fails a (ccons (cV x) e))))')
stubw('d3_Fex', 'paS1Fails_ex_R', ['n', 'a', 't', 'e'],
      'cPr (cIm (cpaS1HeadAt a t) (cIm (cpaTermBound (cSuc (cSuc n)) t) (cIm (cpaTermLowerBound cd2 t) '
      '(ciff (cpaS1Fails (cpaFormulaEx a) e) (cAl x (cpaS1Fails a (ccons (cV x) e)))))))')
stubw('d3_Hal', 'paS1Holds_all_R', ['n', 'a', 'g', 'h', 't', 'e'],
      'cPr (cIm (cEq a (cpaFormulaImp g h)) (cIm (cpaS1HeadAt g t) (cIm (cpaTermBound (cSuc (cSuc n)) t) (cIm (cpaTermLowerBound cd2 t) '
      '(ciff (cpaS1Holds (cpaFormulaAll a) e) (cAl x (cpaS1Holds a (ccons (cV x) e))))))))')
stubw('d3_pre', 'paS1PreAtom_i_R', ['a', 'b'],
      'cPr (cIm (cpaTermLowerBound cd1 a) (cIm (cpaTermLowerBound cd1 b) (cIm (cne a (cpaTermVariable cd1)) '
      '(cIm (cne a (cpaTermSuccessor (cpaTermVariable cd1))) (cpaS1PreAtom (cpaFormulaEx (cpaFormulaEqual (cpaTermAddition a (cpaTermVariable c0)) b)))))))')
add('d3_lea', '(x a b: nat)', ['nfr x a', 'nfr x b'], 'cPr (ciff (cle a b) (cex x (cEq (cAdd a (cV x)) b)))',
    [('a', 'c0'), ('b', 'c0')], ['nfr_c0'] * 2, '(d3r_lealpha_R {h0} {h1})')

def main(out_mm0):
    stubs = subprocess.check_output([sys.executable, os.path.join(HERE, 'stubs.py'), out_mm0, os.path.join(HERE, 'roots_m.txt')],
                                    universal_newlines=True)
    body = open(os.path.join(HERE, 'ev_body.mm1')).read()
    txt = ('import "d3_r.mm1";\n\n-- Route T (lanes/D3CHECK.md), EV: generated by tools/gen7/d3/gen_ev.py. Stub axioms = reflected laws of\n'
           '-- the master reflection RM (tools/gen7/d3/rm.sh), statements verbatim; the linker replaces them by RM\'s proofs.\n'
           + stubs + '\n' + '\n'.join(items) + '\n' + body +
           "\npub theorem d3_ev_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;\n")
    out = os.path.join(ROOT, 'pa-mm0', 'gen7', 'd3_ev.mm1')
    open(out, 'w').write(txt)
    mm0 = subprocess.check_output([sys.executable, os.path.join(HERE, 'mm0of.py'), out], universal_newlines=True)
    open(out[:-1] + '0', 'w').write(mm0)

if __name__ == '__main__':
    main(*sys.argv[1:])
