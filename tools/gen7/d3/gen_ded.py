"""Route T: generates pa-mm0/gen7/d3_ded.mm1 / .mm0, implication forms of the TQ case lemmas (tools/gen7/d3/ded.py)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from ded import wrapper

def Y(s): return '(paFormulaEqual (paTermVariable 0) (paTermLift 1 %s))' % s
P = lambda lvl, f: 'paProvable %s %s' % (lvl, f)
items, specs = [], []
def add(name, binders, hyps, concl, primed, dflt, call):
    txt = wrapper(name, binders, hyps, concl, primed, dflt, call)
    items.append('pub ' + txt)
    specs.append(txt.split(' =\n')[0] + ';')

R0 = '(d3_refl (d3_tlb1 paTermBound_zero))'
for nm, F, T in (('d3c_a', 'trAddF', 'paTermAddition'), ('d3c_m', 'trMulF', 'paTermMultiplication')):
    add(nm + '_i', '(n X Z A B: nat)',
        ['paTermBound n A', 'paTermBound n B', P('(suc n)', '(trIff X %s)' % Y('A')), P('(suc n)', '(trIff Z %s)' % Y('B'))],
        P('(suc n)', '(trIff (%s X Z) %s)' % (F, Y('(%s A B)' % T))),
        [('A', 'paTermZero'), ('B', 'paTermZero'), ('X', Y('paTermZero')), ('Z', Y('paTermZero'))],
        ['paTermBound_zero', 'paTermBound_zero', R0, R0],
        '(%s (d3_iffb1 {h2}) (d3_iffb1 {h3}) {h0} {h1} {h2} {h3})' % nm)
add('d3c_e_i', '(n X Z A B: nat)',
    ['paTermBound n A', 'paTermBound n B', P('(suc n)', '(trIff X %s)' % Y('A')), P('(suc n)', '(trIff Z %s)' % Y('B'))],
    P('(suc n)', '(trIff (trEqF X Z) (paFormulaEqual (paTermLift 1 A) (paTermLift 1 B)))'),
    [('A', 'paTermZero'), ('B', 'paTermZero'), ('X', Y('paTermZero')), ('Z', Y('paTermZero'))],
    ['paTermBound_zero', 'paTermBound_zero', R0, R0],
    '(d3c_e (d3_iffb1 {h2}) (d3_iffb1 {h3}) {h0} {h1} {h2} {h3})')
add('d3_refl_i', '(n A: nat)', ['paFormulaBound n A'], P('n', '(trIff A A)'),
    [('A', 'paFormulaFalse')], ['paFormulaBound_false'], '(d3_refl {h0})')
RF = '(d3_refl (paFormulaBound_false))'
for nm, concl in (('d3p_imp', '(trIff (paFormulaImp X Z) (paFormulaImp Y U))'),
                  ('d3p_and', '(trIff (trNot (paFormulaImp X (trNot Z))) (paFormulaAnd Y U))'),
                  ('d3p_or', '(trIff (paFormulaImp (trNot X) Z) (paFormulaOr Y U))')):
    add(nm + '_i', '(n X Y Z U: nat)', [P('(suc n)', '(trIff X Y)'), P('(suc n)', '(trIff Z U)')], P('(suc n)', concl),
        [('X', 'paFormulaFalse'), ('Y', 'paFormulaFalse'), ('Z', 'paFormulaFalse'), ('U', 'paFormulaFalse')],
        ['(d3_refl paFormulaBound_false)'] * 2,
        '(%s (d3_iffb1 {h0}) (d3_iffb2 {h0}) (d3_iffb1 {h1}) (d3_iffb2 {h1}) {h0} {h1})' % nm)

add('d3_eqhand_i', '(d a b: nat)', ['paTermBound d a', 'paTermBound d b'],
    'paFormulaRename (d3Lv d) 0 (paFormulaEqual a b) = paFormulaEqual (paTermLift 1 (paTermRename (d3L0 d) a)) (paTermLift 1 (paTermRename (d3L0 d) b))',
    [('a', 'paTermZero'), ('b', 'paTermZero')], ['paTermBound_zero', 'paTermBound_zero'], '(d3_eqhand {h0} {h1})')
for nm in ('allq', 'exq'):
    Q = 'paFormulaAll' if nm == 'allq' else 'paFormulaEx'
    add('d3_tq_%s_i' % nm, '(d a N: nat)', ['paFormulaBound (suc d) a',
        P('(suc N)', '(trIff (trPA (d3q (suc d) a)) (paFormulaRename (d3Lv (suc d)) 0 a))')],
        P('(suc N)', '(trIff (trPA (d3q d (%s a))) (paFormulaRename (d3Lv d) 0 (%s a)))' % (Q, Q)),
        [('a', 'paFormulaFalse')], ['paFormulaBound_false', 'd3_qfalse'], '(d3_tq_%s {h0} {h1})' % nm)

hdr = '''import "d3_tq.mm1";

-- Route T, TQ: implication forms of the case lemmas (weak deduction theorem by if-substitution), generated by
-- tools/gen7/d3/gen_ded.py.
'''
PA = os.path.normpath(os.path.join(HERE, '..', '..', '..', 'pa-mm0'))
open(os.path.join(PA, 'gen7', 'd3_ded.mm1'), 'w').write(hdr + '\n' + '\n'.join(items) +
    "\npub theorem d3_ded_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;\n")
open(os.path.join(PA, 'gen7', 'd3_ded.mm0'), 'w').write('import "d3_tq.mm0";\n\n' + '\n'.join(specs) +
    '\ntheorem d3_ded_final: $ paFormulaBound 0 paFormulaFalse $;\n')
print('ok')
