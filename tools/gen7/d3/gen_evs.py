"""Route T, set side: generates pa-mm0/gen7/d3_evs0.mm1 (stubs of the EVS laws + node / congruence lemmas for the
sf constructors) and pa-mm0/gen7/d3_evc.mm1 (numeral evaluation of the closed source formulas used by paFormulaSource:
d3c_D: PA |- [cD = numeral D] for paSourceZero, paSourceSuccessor, paSourceAddition102, paSourceMultiplication102,
paSourceNatural and every closed def below them).
  python3 gen_evs.py RMS/out.mm0        (RMS = tools/gen7/d3/rms.sh's reflection; stubs copied verbatim)"""
import os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
PA = os.path.join(ROOT, 'pa-mm0')
CLOSED = ['paSourceZero', 'paSourceSuccessor', 'paSourceAddition102', 'paSourceMultiplication102', 'paSourceNatural']
BIN = {'sfMem': 'Mem', 'sfEq': 'Eq', 'sfAnd': 'And', 'sfOr': 'Or', 'sfImp': 'Imp'}
UN = {'sfAll': ('All', 6), 'sfEx': ('Ex', 7)}
TAG = {'Mem': 1, 'Eq': 2, 'And': 3, 'Or': 4, 'Imp': 5}
CN = {0: 'd3cn_0', 1: 'd3e_cn1', 2: 'd3e_cn2', 3: 'd3e_cn3', 4: 'd3e_cn4', 5: 'd3e_cn5', 6: 'd3e_cn6', 7: 'd3e_cn7', 8: 'd3e_cn8', 9: 'd3s_cn9'}
LIT = {0: 'c0', 1: 'cd1', 2: 'cd2', 3: 'cd3', 4: 'cd4', 5: 'cd5', 6: 'cd6', 7: 'cd7', 8: 'cd8', 9: 'cd9'}

def stubs(out_mm0, roots):
    return subprocess.check_output([sys.executable, os.path.join(HERE, 'stubs.py'), out_mm0, roots]).decode()

def evs0(out_mm0):
    new = os.path.join(HERE, 'roots_snew.txt')
    L = ['import "d3_evn.mm1";', '',
         '-- Route T, set side (generated by tools/gen7/d3/gen_evs.py): reflected EVS laws (stubs, verbatim from the',
         '-- reflection RMS of gen7/d3_rsrcS), numeral literals, and node / congruence lemmas for the sf constructors:',
         '--   d3s_NK: PA |- [csfK (numeral a) (numeral b) = numeral (sfK a b)],  d3s_HK: the same from [X = numeral a] etc.', '']
    L.append('do {')
    for d in ('csfRenameBody', 'csfRenameStep', 'csfRename', 'cpaSourceTermVariable', 'cpaSourceTermSuccessor',
              'cpaSourceTermAddition', 'cpaSourceTermMultiplication', 'cpaSourceFormulaEqual', 'cpaSourceFormulaAll',
              'cpaSourceFormulaEx', 'cpaTermSourceBody', 'cpaTermSourceStep', 'cpaTermSource', 'cpaFormulaSourceBody',
              'cpaFormulaSourceStep', 'cpaFormulaSource'):
        L.append("  (default-annotate '%s)" % d)
    L.append('};')
    L.append(stubs(out_mm0, new))
    L.append("theorem d3s_cn9: $ d3cn 9 = cd9 $ = '(eqtr d3cn_S (cSuceq d3e_cn8));")
    for k in range(10):
        L.append("theorem d3s_L%d: $ cPr (cEq %s (d3cn %d)) $ = '(mpbir (cPreq (cEqeq eqid %s)) d3r_eqid_R);" % (k, LIT[k], k, CN[k]))
    L.append("theorem d3s_Hsuc (X a: nat) (h: $ cPr (cEq X (d3cn a)) $): $ cPr (cEq (cSuc X) (d3cn (suc a))) $ = '(d3_ceqtr (d3_c1 d3r_suceq_R h) d3_Nsuc);")
    L.append("theorem d3s_NBot: $ cPr (cEq csfBot (d3cn sfBot)) $ = '(mpbir (cPreq (cEqeq eqid d3cn_0)) d3s_kBot_R);")
    for k, t in TAG.items():
        L.append("theorem d3s_N%s (a b: nat): $ cPr (cEq (csf%s (d3cn a) (d3cn b)) (d3cn (sf%s a b))) $ =\n"
                 "'(d3_ceqtr d3s_k%s_R (mpbir (cPreq (cEqeq (csfNodeeq (eqcom %s) eqid eqid) eqid)) d3_Nnode));" % (k, k, k, k, CN[t]))
        L.append("theorem d3s_H%s (X Y a b: nat) (hX: $ cPr (cEq X (d3cn a)) $) (hY: $ cPr (cEq Y (d3cn b)) $):\n"
                 "  $ cPr (cEq (csf%s X Y) (d3cn (sf%s a b))) $ = '(d3_ceqtr (d3_c2 d3s_cg%s_R hX hY) d3s_N%s);" % (k, k, k, k, k))
    for _, (k, t) in UN.items():
        L.append("theorem d3s_N%s (a: nat): $ cPr (cEq (csf%s (d3cn a)) (d3cn (sf%s a))) $ =\n"
                 "'(d3_ceqtr d3s_k%s_R (mpbir (cPreq (cEqeq (csfNodeeq (eqcom %s) eqid (eqcom d3cn_0)) eqid)) d3_Nnode));" % (k, k, k, k, CN[t]))
        L.append("theorem d3s_H%s (X a: nat) (hX: $ cPr (cEq X (d3cn a)) $): $ cPr (cEq (csf%s X) (d3cn (sf%s a))) $ =\n"
                 "'(d3_ceqtr (d3_c1 d3s_cg%s_R hX) d3s_N%s);" % (k, k, k, k, k))
    L += ['', "pub theorem d3_evs0_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;", '']
    return '\n'.join(L)

def read_defs():
    defs = {}
    for f in sorted(os.listdir(PA)):
        if f.endswith('.mm0'):
            for m in re.finditer(r'^def\s+(\w+)\s*:\s*nat\s*=\s*\$(.*?)\$\s*;', open(os.path.join(PA, f)).read(), re.M | re.S):
                defs[m.group(1)] = m.group(2).strip()
    return defs

def parse(s):
    toks = re.findall(r'\(|\)|[A-Za-z_]\w*|\d+', s)
    pos = [0]
    def term():
        t = toks[pos[0]]; pos[0] += 1
        if t == '(':
            h = toks[pos[0]]; pos[0] += 1
            args = []
            while toks[pos[0]] != ')':
                args.append(term())
            pos[0] += 1
            return (h, args)
        return (t, [])
    e = term()
    assert pos[0] == len(toks), s
    return e

def proof(e, defs, need):
    h, args = e
    if h.isdigit():
        k = int(h); assert k in LIT, k
        return 'd3s_L%d' % k
    if h == 'suc':
        assert len(args) == 1
        return '(d3s_Hsuc %s)' % proof(args[0], defs, need)
    if h == 'sfBot' and not args:
        return 'd3s_NBot'
    if h in BIN:
        assert len(args) == 2
        return '(d3s_H%s %s %s)' % (BIN[h], proof(args[0], defs, need), proof(args[1], defs, need))
    if h in UN:
        assert len(args) == 1
        return '(d3s_H%s %s)' % (UN[h][0], proof(args[0], defs, need))
    assert not args and h in defs, h
    need.append(h)
    return 'd3c_' + h

def evc():
    defs = read_defs()
    order, seen = [], set()
    def visit(d):
        if d in seen: return
        seen.add(d)
        need = []
        p = proof(parse('(%s)' % defs[d]), defs, need)
        for n in need: visit(n)
        order.append("theorem d3c_%s: $ cPr (cEq c%s (d3cn %s)) $ = '%s;" % (d, d, d, p))
    for d in CLOSED: visit(d)
    L = ['import "d3_evs0.mm1";', '',
         '-- Route T, set side (generated by tools/gen7/d3/gen_evs.py): numeral evaluation of the closed source formulas',
         '-- below paFormulaSource (%d defs): d3c_D: PA |- [cD = numeral D].' % len(order), ''] + order
    L += ['', "pub theorem d3_evc_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;", '']
    return '\n'.join(L)

def main(out_mm0):
    open(os.path.join(PA, 'gen7/d3_evs0.mm1'), 'w').write(evs0(out_mm0))
    open(os.path.join(PA, 'gen7/d3_evc.mm1'), 'w').write(evc())

if __name__ == '__main__':
    main(*sys.argv[1:])
