"""Route T: generates pa-mm0/d3_adqsrc.mm1 / .mm0, the source of the HOST master reflection for paThPr_D3:
the d3_rsrc laws (imported) + the PA front end's adequacy in implication form + the if-free form of g2paQLCode.
  python3 gen_adqsrc.py            (reads pa-mm0/g2_generic_pa_qlcode.mm0 for g2paQLCode's body)
Reflect it with tools/gen7/d3/roots_adq.txt = roots_m.txt + d3r_adq + d3r_ql (see lanes/D3CHECK.md, HOST NEEDED)."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, os.path.dirname(HERE))
from refl_lib import mm0_statements

def toks(s): return re.findall(r'\(|\)|[^\s()]+', s)
def parse(s):
    t = toks(s); p = [0]
    def e():
        x = t[p[0]]; p[0] += 1
        if x == '(':
            l = []
            while t[p[0]] != ')':
                l.append(e())
            p[0] += 1
            return l[0] if len(l) == 1 else l
        return x
    r = e()
    assert p[0] == len(t)
    return r
def unparse(e): return e if isinstance(e, str) else '(' + ' '.join(unparse(x) for x in e) + ')'

HOLES = {'g2paB1': ('g2paAxV', '(syl ifpos (syl anl anl))'),
         'g2paB2': ('g2paNV', '(syl ifpos (syl anr anl))'),
         'g2paB4': ('g2paSV', '(syl ifpos anr)')}

def has_hole(e): return isinstance(e, list) and (e[0] in HOLES or any(has_hole(x) for x in e[1:]))
def noif(e):
    if isinstance(e, str): return e
    if e[0] in HOLES: return HOLES[e[0]][0]
    return [e[0]] + [noif(x) for x in e[1:]]
def cong(e):
    """proof of G -> e = noif(e)"""
    if not has_hole(e): return '(a1i eqid)'
    if e[0] in HOLES: return HOLES[e[0]][1]
    return '(%seqd %s)' % (e[0], ' '.join(cong(x) for x in e[1:]))

def main():
    txt = open(os.path.join(ROOT, 'pa-mm0', 'g2_generic_pa_qlcode.mm0')).read()
    body = [t for kw, nm, t in mm0_statements(txt) if kw == 'def' and nm.rstrip(':;') == 'g2paQLCode'][0]
    body = body.split('=', 1)[1].strip().rstrip(';').strip().strip('$').strip()
    e = parse(body)
    ni = unparse(noif(e))
    out = []
    out.append('import "g2_generic_pa_thfinal.mm1";\nimport "gen7/d3_rsrc.mm1";\n')
    out.append('-- Route T (lanes/D3CHECK.md): source of the HOST master reflection for paThPr_D3. Generated by\n'
               '-- tools/gen7/d3/gen_adqsrc.py. d3r_adq = adequacy of the PA front end (GEN3: g2paTh_PA_transfer +\n'
               '-- g2paThCode_defines) in implication form; d3r_ql = g2paQLCode without its three bound wrappers.\n')
    out.append(r'''theorem d3r_adq_h (R: nat): $ paFormulaBound 1 (if (paFormulaBound 1 R /\ paS1Class 1 R) R paFormulaFalse) /\
  paS1Class 1 (if (paFormulaBound 1 R /\ paS1Class 1 R) R paFormulaFalse) $ =
'(cases (mpbird (aneqd (paFormulaBoundeqd (a1i eqid) ifpos) (paS1Classeqd (a1i eqid) ifpos)) id)
  (mpbird (aneqd (paFormulaBoundeqd (a1i eqid) ifneg) (paS1Classeqd (a1i eqid) ifneg)) (a1i (iani paFormulaBound_false paS1Class_false))));
theorem d3r_adq_e (A: set) (y: nat) {c: nat}: $ A. c (paProvable 0 c -> paThProvable A c) -> paProvable 0 y -> paThProvable A y $ =
'(!! eale c ,eqtac);
pub theorem d3r_adq (R y: nat): $ paFormulaBound 1 R /\ paS1Class 1 R -> paProvable 0 y -> paS1Holds (g2paThCode R) (y : 0) $ =
(named '(exp (mpbid (paS1Holdseqd (g2paThCodeeqd (syl ifpos anl)) (a1i eqid))
  (syl (bi2i (g2paThCode_defines d3r_adq_h)) (mpd anr (a1i (ax_mp d3r_adq_e g2paTh_PA_transfer)))))));
''')
    out.append('pub theorem d3r_ql (g2paAxV g2paNV g2paSV: nat): $ paFormulaBound 1 g2paAxV -> paFormulaBound 2 g2paNV -> paFormulaBound 4 g2paSV ->\n'
               '  g2paQLCode g2paAxV g2paNV g2paSV = %s $ =\n\'(exp (exp %s));\n' % (ni, cong(e)))
    out.append("pub theorem d3_adqsrc_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;\n")
    p = os.path.join(ROOT, 'pa-mm0', 'd3_adqsrc.mm1')
    open(p, 'w').write('\n'.join(out))
    import subprocess
    open(p[:-1] + '0', 'w').write(subprocess.check_output([sys.executable, os.path.join(HERE, 'mm0of.py'), p], universal_newlines=True))

if __name__ == '__main__':
    main()
