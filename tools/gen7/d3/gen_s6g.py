"""Route T, set side, S6 for the source-graph formula Gsr (lanes/G2GEN.md STATE): PA |- [cbb215L3pGsr = r(bb215L3pGsr)].
  python3 gen_s6g.py MM0DIR --standin          writes pa-mm0/gen7/d3_gsrdefs.mm1 (TEST ONLY: Gsr's closure copied
                                                from the .mm0 files in MM0DIR; imports bb215_sigma1_atom for bb215S1Arg)
  python3 gen_s6g.py MM0DIR OUT.mm0 [--host]   writes pa-mm0/gen7/d3_g0.mm1 (stubs of roots_gnew.txt, verbatim from
                                                the reflection OUT.mm0) and pa-mm0/gen7/d3_s6g.mm1 (the S6 lemmas)
MM0DIR holds the .mm0 files of bb215_derivability_l3p_imp's closure (def bodies and the K_b bound theorems).
Gsr's closure: 290 closed bb215L3* defs (+ bb215S1Arg); 8 of them contain paFormulaRename nodes (27 nodes, all at
depth 0, maps paNatTermConsEnvironment^k (bb215S1Arg 0) v.., 19 distinct renamed defs K).
  rename-free D:     d3g6_D: cD = d3r D                       (META equality, unfolding, as gen_s6.py)
  rename-carrying D: d3g6_D (hyps): cPr (cEq cD (d3r D))      (coded: congruences along the path to each rename node;
                     at a node paFormulaRename M 0 K: d3g_FR0 (d3_frn) with the map hypothesis from d3g_hArg / d3g_hCons
                     and the bound hypothesis hb_K: paFormulaBound n K, n from MM0DIR's K_b theorem)
  d3_S6g (hb_K ..): cPr (cEq cbb215L3pGsr (d3r bb215L3pGsr)); on the host d3_S6gH discharges the hb_K with the K_b."""
import os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.dirname(HERE))
from gen_s6 import load, closure, heads, infer, proof, num_proof, CON, unparse

G7 = os.path.join(ROOT, 'pa-mm0', 'gen7')
TOP = 'bb215L3pGsr'
FBIN = {'paFormulaAnd': ('d3r_cgAnd_R', 'd3r_and'), 'paFormulaOr': ('d3r_cgOr_R', 'd3r_or'), 'paFormulaImp': ('d3r_cgImp_R', 'd3r_imp')}
FUN = {'paFormulaAll': ('d3r_cgAll_R', 'd3r_all'), 'paFormulaEx': ('d3r_cgEx_R', 'd3r_ex')}

def syn_closure(defs):
    return [d for d in closure(defs, [TOP]) if d.startswith('bb215L3')]

def bounds(mm0dir):
    b = {}
    for f in os.listdir(mm0dir):
        if f.endswith('.mm0'):
            for m in re.finditer(r'^theorem (\w+)_b: \$ paFormulaBound (\d+) (\w+) \$;', open(os.path.join(mm0dir, f)).read(), re.M):
                if m.group(1) == m.group(3): b[m.group(3)] = int(m.group(2))
    return b

def standin(mm0dir):
    defs, texts = load(mm0dir)
    syn = syn_closure(defs)
    L = ['-- TEST ONLY stand-in (generated by tools/gen7/d3/gen_s6g.py --standin): the defs of bb215L3pGsr\'s closure,',
         '-- copied from the .mm0 files (bb215S1Arg from the real bb215_sigma1_atom). The host version imports the real modules.',
         'import "../pa_formula_renaming.mm1";', 'import "../pa_source_interpretation_nat_term_assignment.mm1";',
         'import "../bb215_sigma1_atom.mm1";', '']
    for d in syn:
        L.append(texts[d])
    L.append("pub theorem d3g_root: $ %s = %s $ = 'eqid;" % (TOP, TOP))
    L.append("pub theorem d3_gsrdefs_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;")
    p = os.path.join(G7, 'd3_gsrdefs.mm1')
    open(p, 'w').write('\n'.join(L) + '\n')
    print('stand-in defs', len(syn), 'bytes', os.path.getsize(p))

def NUMFIX(t): return re.sub(r'\bd3e_cn(9|1\d)\b', r'd3g_cn\1', t)

def map_proof(e):
    """proof of the map hypothesis A. k cPr (cEq (capp code(e) (d3cn k)) (d3cn (e @ k)))."""
    h, args = e[0], e[1:]
    if h == 'bb215S1Arg':
        return '(d3g_hArg %s)' % NUMFIX(num_proof(args[0], None, {None: {}}))
    if h == 'paNatTermConsEnvironment':
        return '(d3g_hCons %s %s)' % (NUMFIX(num_proof(args[1], None, {None: {}})), map_proof(args[0]))
    raise ValueError(h)

def g6(mm0dir, out_mm0, host):
    defs, texts = load(mm0dir)
    syn = syn_closure(defs)
    bd = bounds(mm0dir)
    dsort, psort = infer(defs, syn)
    ren = set()
    ch = True
    while ch:
        ch = False
        for d in syn:
            if d in ren: continue
            s = set(); heads(defs[d][1], s)
            if 'paFormulaRename' in s or (s & ren): ren.add(d); ch = True
    hyps = {}            # rename-carrying def -> renamed defs K whose bound it needs (transitively)
    def hk(d):
        if d in hyps: return hyps[d]
        out = set()
        def w(e):
            if isinstance(e, str):
                if e in ren: out.update(hk(e))
                return
            if e[0] == 'paFormulaRename':
                out.add(e[3]); w(e[3]); return
            for x in e[1:]: w(x)
        w(defs[d][1])
        hyps[d] = out
        return out
    for d in ren: hk(d)
    allK = sorted(hk(TOP))
    for K in allK:
        assert K in bd, 'no bound theorem for ' + K
    def has_ren(e):
        if isinstance(e, str): return e in ren
        if e[0] == 'paFormulaRename': return True
        return any(has_ren(x) for x in e[1:])
    def fix(t):
        return re.sub(r'\bd3e_cn(9|1\d)\b', r'd3g_cn\1', t).replace('d3s6_bb215L3', 'd3g6m_bb215L3')
    def meta(e):
        return fix(proof(e, '_', defs, dsort, {'_': {}}, 'F'))
    def internal(e):
        """proof of cPr (cEq code(e) (d3r e)) (e a formula)."""
        if not has_ren(e):
            return '(mpbir (cPreq (cEqeq %s eqid)) d3r_eqid_R)' % meta(e)
        if isinstance(e, str):
            return '(d3g6_' + e + ''.join(' hb_' + K for K in sorted(hyps[e])) + ')'
        h, args = e[0], e[1:]
        if h in FBIN:
            cg, dr = FBIN[h]
            return '(mpbi (cPreq (cEqeq eqid (eqcom %s))) (d3_c2 %s %s %s))' % (dr, cg, internal(args[0]), internal(args[1]))
        if h in FUN:
            cg, dr = FUN[h]
            return '(mpbi (cPreq (cEqeq eqid (eqcom %s))) (d3_c1 %s %s))' % (dr, cg, internal(args[0]))
        if h == 'paFormulaRename':
            M, dd, K = args
            assert dd == '0' and isinstance(K, str), e
            return '(d3_ceqtr (d3_c1 d3g_cgFR_R %s) (d3g_FR0 %s hb_%s))' % (internal(K), map_proof(M), K)
        raise ValueError(h)
    nums = set()
    for d in syn: heads(defs[d][1], nums)
    kmax = max([int(x) for x in nums if re.fullmatch(r'\d+', x)] + [10])
    L = ['import "d3_frn.mm1";', 'import "d3_gsrdefs.mm1";' if not host else 'import "../bb215_derivability_l3p_imp.mm1";', '',
         '-- Route T, set side S6 for Gsr (generated by tools/gen7/d3/gen_s6g.py): PA |- [cbb215L3pGsr = r(bb215L3pGsr)].',
         'do {']
    for d in syn:
        L.append("  (default-annotate 'c%s)" % d)
    L.append('};')
    for k in range(9, kmax + 1):
        L.append("theorem d3g_cn%d: $ d3cn %d = cd%d $ = '(eqtr d3cn_S (cSuceq %s));" % (k, k, k, 'd3e_cn8' if k == 9 else 'd3g_cn%d' % (k - 1)))
    L.append("theorem d3g_hArg (J j: nat) {k: nat} (hJ: $ J = d3cn j $): $ A. k cPr (cEq (capp (cbb215S1Arg J) (d3cn k)) (d3cn (bb215S1Arg j @ k))) $ =\n"
             "'(ax_gen (mpbir (cPreq (cEqeq (cappeq (cbb215S1Argeq hJ) eqid) (d3cneq bb215S1Arg_value))) bb215S1Arg_value_R));")
    nm = 0; ni = 0
    for d in syn:
        if d in ren:
            hs = ''.join(' (hb_%s: $ paFormulaBound %d %s $)' % (K, bd[K], K) for K in sorted(hyps[d]))
            L.append("theorem d3g6_%s%s: $ cPr (cEq c%s (d3r %s)) $ =\n(named '%s);" % (d, hs, d, d, internal(defs[d][1])))
            ni += 1
        else:
            L.append("theorem d3g6m_%s: $ c%s = %s %s $ =\n'%s;" % (d, d, {'F': 'd3r', 'T': 'd3rt'}[dsort[d]], d, meta(defs[d][1])))
            nm += 1
    hs = ''.join(' (hb_%s: $ paFormulaBound %d %s $)' % (K, bd[K], K) for K in allK)
    L.append("pub theorem d3_S6g%s: $ cPr (cEq c%s (d3r %s)) $ =\n'%s;" % (hs, TOP, TOP, '(d3g6_' + TOP + ''.join(' hb_' + K for K in allK) + ')'))
    if host:
        L.append("pub theorem d3_S6gH: $ cPr (cEq c%s (d3r %s)) $ =\n'(d3_S6g%s);" % (TOP, TOP, ''.join(' %s_b' % K for K in allK)))
    L.append("pub theorem d3_s6g_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;")
    p = os.path.join(G7, 'd3_s6g.mm1')
    open(p, 'w').write('\n'.join(L) + '\n')
    print('defs', len(syn), 'meta', nm, 'coded', ni, 'bound hyps', len(allK), 'bytes', os.path.getsize(p))
    # stubs for d3_frn
    st = subprocess.check_output([sys.executable, os.path.join(HERE, 'stubs.py'), out_mm0, os.path.join(HERE, 'roots_gnew.txt')], universal_newlines=True)
    G0 = ['import "d3_evs.mm1";', '',
          '-- Route T, set side (generated by tools/gen7/d3/gen_s6g.py): reflected rename laws (stubs, verbatim from the',
          '-- reflection RMG of gen7/d3_rsrcG; the linker replaces them by RMG\'s proofs).',
          "do { (default-annotate 'cbb215S1Arg) (default-annotate 'cpaNatTermConsEnvironment) };", st,
          "pub theorem d3_g0_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;"]
    open(os.path.join(G7, 'd3_g0.mm1'), 'w').write('\n'.join(G0) + '\n')

if __name__ == '__main__':
    a = sys.argv[1:]
    if '--standin' in a:
        standin(a[0])
    else:
        g6(a[0], a[1], '--host' in a)
