"""Route T, set side, S3h (lanes/G2GEN.md STATE; D3CHECK section 1, S3h): the internal inclusion of the ZFC axioms in
the axiom set of R, in the form the set ADQ source takes as its hypothesis:
  d3_S3h (R) (hRb hRc: R of bound 1 in the class) (hgb hgc: the same for g2szRz) (hZ: hZ's 2nd conjunct at g2szRz):
    PA |- [A. x (paS1Holds g2szRz (x : 0) -> paS1Holds (r R) (x : 0))]   (binder = name 0)
Inside PA: hZ lifted to level suc N, TQ (d3_TQ) turns it into the coded A. 0 (q(g2szRz) -> q(R)), U3h (d3u_U) at
g2szRz and at R replaces both sides by the coded Holds, and S6 for g2szRz (generated below) gives [cg2szRz = r g2szRz].
(zfcAxioms C_ g2sfAxSet R follows from this inside the ADQ source, by g2szRz_axioms, on the host.)
  python3 gen_s3h.py MM0DIR --standin    writes pa-mm0/gen7/d3_szdefs.mm1 (TEST ONLY: g2szRz's closure copied)
  python3 gen_s3h.py MM0DIR [--host]     writes pa-mm0/gen7/d3_s3h.mm1
MM0DIR holds the .mm0 files of g2_generic_sz_rec's closure."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.dirname(HERE))
from gen_s6 import load, closure, heads, infer, proof, RR

G7 = os.path.join(ROOT, 'pa-mm0', 'gen7')
TOP = 'g2szRz'

def own(defs):
    return [d for d in closure(defs, [TOP]) if d.startswith('g2s')]

def standin(mm0dir):
    defs, texts = load(mm0dir)
    L = ['-- TEST ONLY stand-in (generated by tools/gen7/d3/gen_s3h.py --standin): the defs of g2szRz\'s closure, copied',
         '-- from the .mm0 files (GEN2 g2_generic_sz_rec, GEN3 g2_generic_s1_tbase). The host version imports the real modules.',
         'import "../pa_formula_syntax.mm1";', '']
    for d in own(defs):
        L.append(texts[d].replace('def ', '@_ def ', 1) if not texts[d].startswith('@_') else texts[d])
    L.append("pub theorem d3z_root: $ %s = %s $ = 'eqid;" % (TOP, TOP))
    L.append("pub theorem d3_szdefs_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;")
    open(os.path.join(G7, 'd3_szdefs.mm1'), 'w').write('\n'.join(L) + '\n')
    print('stand-in defs', len(own(defs)))

S3H = r'''
-- S3h
theorem d3z_q0 (R: nat): $ d3q 0 (paFormulaAll (paFormulaImp g2szRz R)) = cAl 0 (cIm (d3q 1 g2szRz) (d3q 1 R)) $ =
'(eqtr d3q_all (cAleq eqid d3q_imp));
theorem d3z_h0 (c: nat): $ 0 + c <= c $ = '(mpbir (leeq1 add01) leid);
theorem d3z_up (R: nat) (hZ: $ paProvable 0 (paFormulaAll (paFormulaImp g2szRz R)) $):
  $ cPr (cAl 0 (cIm (d3q 1 g2szRz) (d3q 1 R))) $ =
(named '(mpbi (cPreq d3z_q0) (mpbir (g7_cpr_iff (d3_cb d3z_h0))
  (bb215D2_mp (mpbi (paProvableeq1 add01) (bb215D2_raise hZ))
    (bb215D2_and_right (mpbi (paProvableeq2 (trIffeq eqid (paFormulaRename_closed (paProvable_bound hZ)))) (d3_TQ (paProvable_bound hZ) d3z_h0)))))));
pub theorem d3_S3h (R: nat) (hRb: $ paFormulaBound 1 R $) (hRc: $ paS1Class 1 R $)
  (hgb: $ paFormulaBound 1 g2szRz $) (hgc: $ paS1Class 1 g2szRz $) (hZ: $ paProvable 0 (paFormulaAll (paFormulaImp g2szRz R)) $):
  $ cPr (cAl 0 (cIm (cpaS1Holds cg2szRz (ccons (cV 0) c0)) (cpaS1Holds (d3r R) (ccons (cV 0) c0)))) $ =
(named '(mpbir (cPreq (cAleq eqid (cImeq (cpaS1Holdseq d3z6_g2szRz eqid) eqid)))
  (d3_cbi1 (d3_c1 d3r_aleq_R (d3_cgen (d3_c2 d3r_imeq_R (d3u_U hgb hgc) (d3u_U hRb hRc)))) (d3z_up hZ))));
'''

def gen(mm0dir, host):
    defs, texts = load(mm0dir)
    lem = own(defs)
    dsort, psort = infer(defs, lem)
    nums = set()
    for d in lem: heads(defs[d][1], nums)
    kmax = max([int(x) for x in nums if re.fullmatch(r'\d+', x)] + [10])
    def fix(t):
        t = re.sub(r'\bd3e_cn(9|[1-9]\d)\b', r'd3z_cn\1', t)
        return re.sub(r'\bd3s6_(g2s\w*)', r'd3z6_\1', t)
    L = ['import "d3_un.mm1";', 'import "d3_szdefs.mm1";' if not host else 'import "../g2_generic_sz_rec.mm1";', '',
         '-- Route T, set side S3h (generated by tools/gen7/d3/gen_s3h.py; see its docstring).', 'do {']
    for d in lem: L.append("  (if (def? (get-decl 'c%seqd)) () (default-annotate 'c%s))" % (d, d))  # guarded: g7_s6sf annotates the shared cg2s1* too
    L.append('};')
    for k in range(9, kmax + 1):
        L.append("theorem d3z_cn%d: $ d3cn %d = cd%d $ = '(eqtr d3cn_S (cSuceq %s));" % (k, k, k, 'd3e_cn8' if k == 9 else 'd3z_cn%d' % (k - 1)))
    for d in lem:
        vs = defs[d][0]
        bind = ' (%s: nat)' % ' '.join(vs) if vs else ''
        lhs = 'c%s%s' % (d, ''.join(' (%s %s)' % (RR[psort[d].get(v, 'F')], v) for v in vs)) if vs else 'c' + d
        rhs = '%s %s' % (RR[dsort[d]], '(%s %s)' % (d, ' '.join(vs)) if vs else d)
        L.append("theorem d3z6_%s%s: $ %s = %s $ =\n'%s;" % (d, bind, lhs, rhs, fix(proof(defs[d][1], d, defs, dsort, psort, dsort[d]))))
    L.append(S3H)
    if host:
        L.append("pub theorem d3_S3hH (R: nat) (hR: $ paFormulaBound 1 R /\\ paS1Class 1 R $) (hZ: $ paProvable 0 (paFormulaAll (paFormulaImp g2szRz R)) $):\n"
                 "  $ cPr (cAl 0 (cIm (cpaS1Holds cg2szRz (ccons (cV 0) c0)) (cpaS1Holds (d3r R) (ccons (cV 0) c0)))) $ =\n"
                 "'(d3_S3h (anli hR) (anri hR) g2szRz_bound g2szRz_class hZ);")
    L.append("pub theorem d3_s3h_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;")
    p = os.path.join(G7, 'd3_s3h.mm1')
    open(p, 'w').write('\n'.join(L) + '\n')
    print('S6 lemmas', len(lem), 'bytes', os.path.getsize(p))

if __name__ == '__main__':
    a = sys.argv[1:]
    if '--standin' in a: standin(a[0])
    else: gen(a[0], '--host' in a)
