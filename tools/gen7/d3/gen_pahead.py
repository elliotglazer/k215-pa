r"""G2GEN PA front end: writes the headline modules of section (B-PA) of targets/g2_generic.mm0.
  python3 tools/gen7/d3/gen_pahead.py            (from the repo root)
Writes pa-mm0/gen7/{g2pa_head, g2pa_headt, g2pa_spec}.{mm1,mm0}:
  g2pa_head   HOST module: the three headline theorems in the literal readings (paThCode := g2paThCode, paThAxSet :=
              g2paAxSet, thIsSigma1Rec R := paFormulaBound 1 R /\ paS1Class 1 R). Imports GEN3's thd2 (D1, D2, fixed point,
              g2paAxSet_value), route T's d3_pad3 (D3) and gen7/g2pa_bb (the real general-predicate core). The run cut
              tm_run_cut enters as ONE stub axiom (spec text), resolved by the staged run-cut link (C5: g7_hD + GEN4's
              g2_generic_tm_runcut + g7c5_gen4).
  g2pa_headt  TEST ONLY: the same proof text; GEN3's / route T's facts and tm_run_cut as stub axioms with their
              statements copied verbatim from the proving modules' .mm0 (list STUBS below), defs from the TEST ONLY
              stand-in d3_s6defs plus a verbatim copy of g2paAxSet.
  g2pa_spec   the spec text verbatim: defines the abstract defs of g2_generic_defs.mm0 that the (B-PA) statements use at
              the literal readings and proves G2_generic_pa, BB_generic_pa_thm2, BB_generic_pa_thm3 by unfolding.
              Imports gen7/g2pa_head (locally replaced by a shim importing g2pa_headt, see check_pahead.sh)."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
PA = os.path.join(ROOT, 'pa-mm0')

def stmt(path, name):
    s = open(os.path.join(PA, path)).read()
    m = re.search(r'(?m)^(?:pub )?(?:theorem|axiom) %s\b' % re.escape(name), s)
    if not m: raise SystemExit('no %s in %s' % (name, path))
    i = m.start() + (4 if s[m.start():].startswith('pub ') else 0)
    i = s.index(' ', i) + 1
    return s[i:s.index('$;', i) + 1]

# (statement, proving module .mm0, where it is checked)
STUBS = [('g2paAxSet_value', 'g2_generic_pa_axcode.mm0'),
         ('g2paThCode_bound', 'g2_generic_pa_thfinal.mm0'),
         ('g2paThCode_D1', 'g2_generic_pa_thfinal.mm0'),
         ('g2paThCode_fixed_point', 'g2_generic_pa_thfinal.mm0'),
         ('g2paThCode_D2', 'g2_generic_pa_thd2.mm0'),
         ('g2paThCode_D3', 'gen7/d3_pad3.mm0'),
         ('tm_run_cut', 'targets/g2_generic.mm0')]
SPEC = 'targets/g2_generic.mm0'
HR = '$ paFormulaBound 1 R /\\ paS1Class 1 R $'
AX = 'g2paAxSet R'
HA = '(ax_gen (syl anl (bi1 g2paAxSet_value)))'
PKG = '%s g2paThCode_bound (g2paThCode_D1 hR) g2paThCode_D2 (g2paThCode_D3 hR) g2paThCode_fixed_point' % HA
HEAD = """-- Literal readings (as C5's, to be confirmed at the freeze): paThCode R := g2paThCode R (GEN3), paThAxSet R := g2paAxSet R,
-- paSigma1 c := paS1Class 1 c, paSigma1True c a := paS1Holds c (a : 0); so thIsSigma1Rec R = paFormulaBound 1 R /\\ paS1Class 1 R.
pub theorem G2_generic_paL (R: nat) (hR: %(HR)s):
  $ ~paThProvable (%(AX)s) paFormulaFalse -> ~paThProvable (%(AX)s) (bb215ProvabilityConsistencyPA (g2paThCode R)) $ =
(named '(G2_abstract_pa %(PKG)s));

pub theorem BB_generic_pa_thm2L (R m n M: nat) {b: nat} (hR: %(HR)s)
  (hM: $ tmValid m M $) (hmn: $ m <= n $)
  (hT1: $ tmHalts m M <-> paThProvable (%(AX)s) paFormulaFalse $)
  (hB: $ bb215ProvabilityInternalBridge (g2paThCode R) (tmHaltsPA m M) $):
  $ ~paThProvable (%(AX)s) paFormulaFalse <-> A. b ~paThProvable (%(AX)s) (bbSentencePA n b) $ =
(named '(g2pb_thm2_P %(PKG)s hT1 hB (tm_run_cut hM hmn)));

pub theorem BB_generic_pa_thm3L (R m n M: nat) {b: nat} (hR: %(HR)s)
  (hM: $ tmValid m M $) (hmn: $ m <= n $)
  (hT1: $ tmHalts m M <-> paThProvable (%(AX)s) paFormulaFalse $)
  (hB: $ bb215ProvabilityInternalBridge (g2paThCode R) (tmHaltsPA m M) $):
  $ (~paThProvable (%(AX)s) paFormulaFalse <-> ~tmHalts m M) /\\
    (~tmHalts m M <-> A. b ~paThProvable (%(AX)s) (bbSentencePA n b)) $ =
(named '(g2pb_thm3_P %(PKG)s hT1 hB (tm_run_cut hM hmn)));

pub theorem g2paHead_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;
""" % dict(HR=HR, AX=AX, PKG=PKG)

def g2paAxSet_def():
    s = open(os.path.join(PA, 'g2_generic_pa_axcode.mm0')).read()
    i = s.index('def g2paAxSet ')
    return s[i:s.index('$;', i) + 2]

def main():
    gd = os.path.join(PA, 'gen7')
    stubs = {n: stmt(p, n) for n, p in STUBS}
    w = lambda f, t: open(os.path.join(gd, f), 'w', newline='\n').write(t)
    hdr = '-- GENERATED by tools/gen7/d3/gen_pahead.py (lane G2GEN, PA front end). Do not edit.\n'
    # host module
    host = ('import "../g2_generic_pa_thd2.mm1";\nimport "d3_pad3.mm1";\nimport "g2pa_bb.mm1";\n\n' + hdr +
            '-- HOST module. tm_run_cut (spec text) is a stub, resolved by the staged run-cut link (lanes/G2GEN.md PA FRONT END).\n'
            'axiom %s;\n\n' % stubs['tm_run_cut'] + HEAD)
    w('g2pa_head.mm1', host)
    # test module
    test = ('import "g2pa_bb.mm1";\nimport "d3_s6defs.mm1";\nimport "../bb215_provability_fixed_point.mm1";\n\n' + hdr +
            '-- TEST ONLY: proof text of g2pa_head; stand-in defs (d3_s6defs + g2paAxSet copied verbatim) and stub axioms\n'
            '-- copied verbatim from the proving modules: ' + ', '.join('%s (%s)' % x for x in STUBS) + '.\n' +
            '@_ ' + g2paAxSet_def() + '\n' + ''.join('axiom %s;\n' % stubs[n] for n, _ in STUBS) + '\n' + HEAD)
    w('g2pa_headt.mm1', test)
    # spec-text module
    sp = open(os.path.join(PA, SPEC)).read()
    G2 = stmt(SPEC, 'G2_generic_pa'); T2 = stmt(SPEC, 'BB_generic_pa_thm2'); T3 = stmt(SPEC, 'BB_generic_pa_thm3')
    defs = ('@_ def paSigma1 (c: nat): wff = $ paS1Class 1 c $;\n'
            '@_ def paSigma1True (c a: nat): wff = $ paS1Holds c (a : 0) $;\n'
            '@_ def thIsSigma1Rec (R: nat): wff = $ paFormulaBound 1 R /\\ paSigma1 R $;\n'
            '@_ def paThAxSet (R .a: nat): set = $ {a | paFormulaBound 0 a /\\ paSigma1True R a} $;\n'
            '@_ def paThInconsistent (R: nat): wff = $ paThProvable (paThAxSet R) paFormulaFalse $;\n'
            '@_ def paThCode (R: nat): nat = $ g2paThCode R $;\n'
            '@_ def paThPr (R: nat): nat = $ paThCode R $;\n'
            '@_ def paThCon (R: nat): nat = $ bb215ProvabilityConsistencyPA (paThPr R) $;\n')
    spec = ('import "g2pa_head.mm1";\n\n' + hdr +
            '-- (B-PA) of targets/g2_generic.mm0, statements VERBATIM; the abstract defs paSigma1, paSigma1True, paThCode at the\n'
            '-- literal readings, the other defs with the bodies of g2_generic_defs.mm0.\n' + defs + '\n' +
            "pub theorem %s =\n(named '(G2_generic_paL hR));\n\n" % G2 +
            "pub theorem %s =\n(named '(BB_generic_pa_thm2L hR hM hmn hT1 hB));\n\n" % T2 +
            "pub theorem %s =\n(named '(BB_generic_pa_thm3L hR hM hmn hT1 hB));\n\n" % T3 +
            "pub theorem g2paSpec_final: $ paFormulaBound 0 paFormulaFalse $ = 'paFormulaBound_false;\n")
    w('g2pa_spec.mm1', spec)
    # check: the spec-text defs agree with g2_generic_defs.mm0 except for the three abstract ones
    gdefs = open(os.path.join(PA, 'g2_generic_defs.mm0')).read()
    for line in defs.splitlines():
        nm = re.match(r'@_ def (\w+)', line).group(1)
        g = re.search(r'(?m)^def %s\b[^;]*;' % nm, gdefs).group(0)
        mine = line[len('@_ '):]
        if nm in ('paSigma1', 'paSigma1True', 'paThCode'):
            assert g.split(':')[0] == mine.split(':')[0] and g.endswith(';') and '=' not in g, (nm, g)
        else:
            assert g == mine, (nm, g, mine)
    print('ok: g2pa_head, g2pa_headt, g2pa_spec; defs agree with g2_generic_defs.mm0 (3 abstract at readings)')

if __name__ == '__main__':
    main()
