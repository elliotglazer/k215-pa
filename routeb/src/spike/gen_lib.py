"""Generate spike/negtrans-lib.mm1: the hand-written HA-side library for the
negative+Friedman translation of peano with nat terms as graphs (SPIKE).

Proofs marked L"..." are lambda terms compiled to ax_1/ax_2/ax_mp by lamc.py
(@L"..." inlines one inside a larger proof).
Convention (matched by translator/negtrans.py): the Friedman formula A is the
LAST argument of every translated def and theorem; a peano nat metavariable
`a` becomes a set variable (the graph of `a`), and side hypotheses
(`dn p A -> p` for wff variables, `nsing a A` for nat variables) come after
the translated hypotheses, in argument order.  Plain Goedel-Gentzen is the
instance A := F.

Graphs: a nat term t becomes a set t^G with `y e. t^G` meaning "y is t":
  x^G = sg x = {y | y = x}   (bound variables and 0)
  (suc a)^G = sucG a^G,  (a + b)^G = addG a^G b^G,  (a * b)^G = mulG a^G b^G
  (the S)^G = theG S^ :  y = the S  iff  (S is {w} -> y = w) and
                                          (S is no singleton -> y = 0)
  a = b  |->  eqG a^G b^G A,   a e. S  |->  elG a^G S^ A
`nsing X A` (X is negatively a singleton) holds for every translated term:
ns_sg, ns_suc, ns_add, ns_mul, ns_the (the last for ANY set S).
"""
