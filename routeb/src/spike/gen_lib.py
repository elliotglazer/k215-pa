def ald(n):
    vs = " ".join("a%d" % i for i in range(1, n + 1))
    hyp = " -> ".join("a%d" % i for i in range(1, n + 1))
    body = "[ax_gen h]"
    for i in range(1, n + 1):
        body = "([alnf] %s e%d)" % (body, i)
    lam = body
    for i in range(n, 0, -1):
        lam = "(\\ e%d %s)" % (i, lam)
    return ('theorem ald%d {x: nat} (%s: wff) (p: wff x) (h: $ %s -> p $):\n'
            '  $ %s -> A. x p $ = L"%s";\n' % (n, vs, hyp, hyp, lam))


