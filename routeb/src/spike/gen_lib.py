def expand(text):
    # L"..." (whole quoted proof) and @L"..." (inline sub-proof)
    text = re.sub(r'@L"([^"]*)"', lambda m: compile_lam(m.group(1)), text)
    text = re.sub(r'L"([^"]*)"', lambda m: "'" + compile_lam(m.group(1)), text)
    return text


def build():
    parts = [BASE, "".join(ald(n) for n in range(1, 8)), BASE2]
    for op, sym, eq in (("add", "+", "addeq"), ("mul", "*", "muleq")):
        b = BIN.replace("OPG", op + "G").replace("SYM", sym).replace("OPeqN", eq + "N")
        b = b.replace("OPeq", eq).replace("OPq0", op + "4").replace("elOPE", "el" + op + "E")
        b = b.replace("elOPI", "el" + op + "I").replace("ns_OP", "ns_" + op)
        b = re.sub(r"\bOP(a\d|q\d|e4)", op + r"OP\1", b)
        parts.append(b)
    parts += [AXIOMS, AX2, THE]
    return expand("".join(parts)).lstrip()


