"""B6 library generator: the HA-side library the B6 driver translates against.

  python3 b6/gen_lib.py [--set thm1|b4b] [--tools DIR] [--out DIR]     # from anywhere

--set thm1 (default): K215 Theorem 1 (B6), output b6-lib.mmb as described below.
--set b4b: K215 Theorems 1, 2, 3 and G2 (B6b): the bd defs of b4/bd_certs.mm0 AND
b4/bd_certs_b4b.mm0 (3,413 defs, both files' text verbatim), their translated defs and
per-def lemmas, and the recovery lemmas of the seven Pi2 targets (K215_sigma1/2 and the
five B4b targets); output b6-lib-b4b.mmb (OUT defaults to build/b6b).

It is the B5 library (b5/gen_b5.py) restricted to what K215 Theorem 1 needs:
hpeano + the approved bd defs of b4/bd_certs.mm0 (read over hpeano, verbatim
text) + the spike graph library + the translated support/bd defs (exactly as
translator.negtrans makes them, which the translator re-checks) + the B5
schemas (b5/hand.mm1t) + isv_D / rel_D / dec_D for every bd def + the two
recovery lemmas rec_K215_sigma1 / rec_K215_sigma2 (and ren_bdZfcBot /
ren_bdK215Halt). No test defs.

Steps (all from sources): compile foundation/peano.mm1 + bd defs (pass-A
source) and spike/negtrans-lib.mm1 with mm0-rs; translate the pass-A source to
read off the translated defs; write b6-lib.mm1; compile it to b6-lib.mmb; check
it with mm0-c against hpeano.mm0 + the bd defs. Output: OUT/b6-lib.mm1,
OUT/b6-lib.mmb (OUT defaults to build/b6). b6/b6-lib.mmb in git is a copy of
that file, pinned by sha256 in b6/b6.py.
"""
import hashlib
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "b5"))
sys.path.insert(0, os.path.join(ROOT, "spike"))

import gen_b5  # noqa: E402

# (name, kind, src theorem, D, D') as in gen_b5.RECS; only kind matters for
# the recovery lemma text, which is the same for 'closed' and 'closedhyp'.
RECS = [
    ("K215_sigma1", "closed", "K215_sigma1", "bdK215Halt", "bdZfcBot"),
    ("K215_sigma2", "closed", "K215_sigma2", "bdZfcBot", "bdK215Halt"),
]
# per set: bd-def set of gen_b5.BD_SETS, recovery targets, library file stem, default OUT
SETS = {
    "thm1": dict(bd="b4", recs=RECS, stem="b6-lib", out="b6"),
    "b4b": dict(bd="b4b", recs=RECS + [(n, "closed", n, d, e) for n, _, _, d, e in gen_b5.RECS_B4B],
                stem="b6-lib-b4b", out="b6b"),
}


def exe(tools, name):
    for n in (name + ".exe", name):
        p = os.path.join(tools, n)
        if os.path.isfile(p):
            return p
    raise SystemExit("no %s in %s" % (name, tools))


def run(cmd, stdin=None, cwd=None):
    with open(stdin, "rb") if stdin else open(os.devnull, "rb") as f:
        r = subprocess.run(cmd, stdin=f, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, cwd=cwd)
    return r.returncode, r.stdout.decode(errors="replace")


def compile_mm1(rs, path, out):
    rc, log = run([rs, "compile", path, out], cwd=os.path.dirname(path))
    bad = [l for l in log.splitlines() if "error" in l.lower() or "sorry" in l]
    if rc or bad:
        print(log[-12000:])
        raise SystemExit("compile failed: " + path)


def lib_spec_text(which="thm1"):
    """hpeano.mm0 + the bd defs: the public part of the library."""
    with open(os.path.join(ROOT, "foundation", "hpeano.mm0"), newline="") as f:
        return f.read() + gen_b5.bd_body(SETS[which]["bd"])


def build(tools, out, which="thm1"):
    cfg = SETS[which]
    bd = gen_b5.bd_body(cfg["bd"])
    stem = cfg["stem"]
    from translator.mmb_reader import read_mmb
    from translator.negtrans import NegTrans
    rs, mc = exe(tools, "mm0-rs"), exe(tools, "mm0-c")
    os.makedirs(out, exist_ok=True)
    # the mm1 files import "../foundation/*.mm1" relative to their location
    fdir = os.path.join(out, "foundation")
    os.makedirs(fdir, exist_ok=True)
    for f in ("peano.mm1", "peano.mm0", "hpeano.mm0"):
        shutil.copyfile(os.path.join(ROOT, "foundation", f), os.path.join(fdir, f))
    wdir = os.path.join(out, "lib")
    os.makedirs(wdir, exist_ok=True)
    # pass A source: peano + bd defs
    srcp = os.path.join(wdir, stem + "src.mm1")
    with open(srcp, "w", newline="\n") as f:
        f.write('-- GENERATED by b6/gen_lib.py: peano + B4 bd defs (pass-A source).\n'
                'import "../foundation/peano.mm1";\n' + bd)
    src_mmb = os.path.join(wdir, stem + "src.mmb")
    compile_mm1(rs, srcp, src_mmb)
    spikep = os.path.join(wdir, "negtrans-lib.mm1")
    shutil.copyfile(os.path.join(ROOT, "spike", "negtrans-lib.mm1"), spikep)
    spike_mmb = os.path.join(wdir, "negtrans-lib.mmb")
    compile_mm1(rs, spikep, spike_mmb)
    src = read_mmb(src_mmb)
    tr = NegTrans(src, read_mmb(spike_mmb))
    tr.run()
    names = ["d%d" % i for i in range(1, 11)] + ["ne"] + gen_b5.def_names(bd)
    want = set(gen_b5.SUPPORT) | set(gen_b5.def_names(bd))
    tdefs = []
    for t in src.terms:
        if t.name in want:
            d = tr.terms[tr.tname[t.name + "_N"]]
            tdefs.append("local " + tr.print_decl(d, True))
    gtext = gen_b5.Gen(src).run(set(names))
    saved = gen_b5.RECS
    gen_b5.RECS = cfg["recs"]
    try:
        rtext = gen_b5.expand(gen_b5.rec_text())
    finally:
        gen_b5.RECS = saved
    hand = gen_b5.expand(open(os.path.join(ROOT, "b5", "hand.mm1t")).read())
    lib = ('-- %s.mm1 -- GENERATED by b6/gen_lib.py; do not edit.\n'
           '-- hpeano + %s bd defs (hpeano reading) + spike graph library + translated defs\n'
           '-- + B5 recovery schemas (b5/hand.mm1t) + generated per-def lemmas + K215 recovery lemmas.\n'
           % (stem, "B4" if which == "thm1" else "B4 + B4b") +
           'import "../foundation/hpeano.mm0";\n' + bd +
           "\n-- ===== spike graph library (spike/negtrans-lib.mm1) =====\n" + gen_b5.spike_lib_body() +
           "\n-- ===== translated defs (exactly as translator.negtrans makes them) =====\n" +
           "\n".join(tdefs) + "\n\n" + hand + "\n" + gtext + "\n" + rtext)
    libp = os.path.join(wdir, stem + ".mm1")
    with open(libp, "w", newline="\n") as f:
        f.write(lib)
    lib_mmb = os.path.join(out, stem + ".mmb")
    compile_mm1(rs, libp, lib_mmb)
    shutil.copyfile(libp, os.path.join(out, stem + ".mm1"))
    spec = os.path.join(out, stem + ".spec.mm0")
    with open(spec, "w", newline="") as f:
        f.write(lib_spec_text(which))
    rc, log = run([mc, lib_mmb], stdin=spec)
    if rc:
        print(log[-4000:])
        raise SystemExit("mm0-c rejects %s.mmb" % stem)
    h = hashlib.sha256(open(lib_mmb, "rb").read()).hexdigest()
    return lib_mmb, h


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(prog="b6/gen_lib.py")
    ap.add_argument("--set", default="thm1", choices=sorted(SETS))
    ap.add_argument("--tools", default=os.path.join(ROOT, "tools"))
    ap.add_argument("--out", default=None)
    ns = ap.parse_args(argv)
    out = ns.out or os.path.join(ROOT, "build", SETS[ns.set]["out"])
    p, h = build(os.path.abspath(ns.tools), os.path.abspath(out), ns.set)
    print("%s sha256 %s" % (p, h))


if __name__ == "__main__":
    main()
