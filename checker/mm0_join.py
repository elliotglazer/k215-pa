"""Byte-exact replica of `mm0-rs join IN OUT` (default: comments and header), as check.py runs it on the
proof host (cwd = pa-mm0, Windows path separators in the per-file banners).

Model: mm0-rs/src/joiner.rs (digama0/mm0 master). The output is a header naming the input file and every
joined file (base names, post order), then each file's text with every `import` statement replaced by the
joined text of the imported file (each file once) plus a newline, and a banner `-- <path relative to cwd>
--` framed by dashes before the rest of the file. Validated against the pinned host mm0-rs: the SHA-256 of
this replica equals report.json's spec_sha256 for 147 of 147 PASSED reports whose .mm0 sources are
unchanged, closures of 1 to 948 files.

    python3 -I checker/mm0_join.py FILE.mm0 [CWD]   -> prints sha256 and length of the joined spec
"""
import hashlib, os, re, sys

def stmts_imports(text):
    """Spans of top-level `import "f";` statements, skipping comments, math strings and strings."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if text.startswith('--', i):
            j = text.find('\n', i); i = n if j < 0 else j + 1; continue
        if c == '$':
            j = text.find('$', i + 1); i = j + 1; continue
        if text.startswith('import', i) and (i == 0 or not (text[i-1].isalnum() or text[i-1] == '_')):
            m = re.compile(r'import\s+"([^"]+)"\s*;').match(text, i)
            if m:
                out.append((m.start(), m.end(), m.group(1))); i = m.end(); continue
        i += 1
    return out

def rel(path, cwd, sep):
    r = os.path.relpath(path, cwd)
    return r.replace(os.sep, sep)

def join(top, cwd, sep='\\'):
    working, done, buf = set(), [], []
    def write(path):
        text = open(path, 'rb').read().decode('utf-8')
        start = 0
        for s, e, f in stmts_imports(text):
            r = os.path.realpath(os.path.join(os.path.dirname(path), f))
            buf.append(text[start:s])
            if r not in working:
                working.add(r)
                write(r)
                buf.append('\n')
            start = e
        rp = rel(path, cwd, sep)
        d = '-' * (len(rp) + 6)
        buf.append('%s\n-- %s --\n%s\n' % (d, rp, d))
        buf.append(text[start:])
        done.append(path)
    top = os.path.realpath(top)
    write(top)
    hdr = ('-- This is an autogenerated file constructed by `mm0-rs join %s`.\n'
           '-- It concatenates the files:\n' % os.path.basename(top))
    hdr += ''.join('-- * %s\n' % os.path.basename(p) for p in done) + '\n'
    return (hdr + ''.join(buf)).encode('utf-8')

if __name__ == '__main__':
    cwd = sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(os.path.realpath(sys.argv[1]))
    b = join(sys.argv[1], cwd)
    print(hashlib.sha256(b).hexdigest(), len(b))
